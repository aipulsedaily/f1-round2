def selftest():
    ok = [True]

    def chk(msg, cond, extra=""):
        ok[0] = ok[0] and bool(cond)
        print("   %s  %s%s" % ("PASS" if cond else "FAIL", msg,
                               ("   [%s]" % extra) if extra else ""))

