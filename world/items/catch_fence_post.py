def post_acc(p, lod=None):
    """Everything about one post, in its own local frame.  -> (Acc, cutters)"""
    lod = int(p.lod if lod is None else lod)
    acc = Acc(p.name)
    post_shell(acc, p, lod, mat=0)
    cut = build_head(acc, p, lod, mat=0)
    build_cleats(acc, p, lod, mat=0, mat_bolt=1)
    build_base(acc, p, lod, mat=0, mat_bolt=1, mat_conc=2)
    build_raker(acc, p, lod, mat=0, mat_bolt=1)
    build_splice(acc, p, lod, mat=0, mat_bolt=1)
    build_tag(acc, p, lod, mat=0)
    build_mark(acc, p, lod, mat=0)
    build_cap(acc, p, lod, mat=0)
    if LOD_SPEC[lod]["holes"]:
        sec = p.sec
        for sh in p.spare_holes:
            if sec.kind == "SHS":
                break
            Cc, eu, ev = post_frames(p, np.array([sh["z"]]))
            n = ev[0] * sh["face"]
            o = Cc[0] + n * (0.5 * sec.D)
            cut.append(dict(o=o - n * 0.006, a=n, r=sh["d"] * 0.5,
                            depth=sec.tf + 0.014))
    else:
        cut = []
    return acc, cut


def _punch(ob, cutters, lod):
    """Drill the spare and splice holes as REAL holes.

    A hole that is not a hole is the thing this campaign exists to catch: a
    14 mm hole is 20 px at the filmed distance, it has a wall, and light
    reaches into it and does not come back.

    Blender's boolean does not carry generic attributes onto the vertices it
    creates, so every vertex is re-attributed afterwards from the nearest
    ORIGINAL vertex, and anything that ended up on a bore wall is marked bare
    (a drilled edge has no zinc on it, which is why it is the first place a
    galvanised post rusts).
    """
    if not cutters:
        return 0
    me = ob.data
    n0 = len(me.vertices)
    co0 = np.empty(n0 * 3, np.float32)
    me.vertices.foreach_get("co", co0)
    co0 = co0.reshape(-1, 3).astype(np.float64)
    A0 = {}
    for a in ATTR_F:
        at = me.attributes.get(PFX.lower() + a)
        v = np.empty(n0, np.float32)
        at.data.foreach_get("value", v)
        A0[a] = v
    # ONE cutter mesh for all the holes, not one boolean each: the exact solver
    # rebuilds the whole 190 k-triangle post per modifier, so twelve holes done
    # twelve times is twelve times the cost for the same result.
    allV, allF = [], []
    nseg = 24 if lod >= 3 else 14
    for c in cutters:
        o, a, e1, e2 = _fr(c["o"], c["a"])
        ang = np.arange(nseg) * (2 * math.pi / nseg)
        rr = c["r"]
        b = len(allV) and sum(len(v) for v in allV) or 0
        V = []
        for zz in (0.0, c["depth"]):
            V.append(o + a * zz + e1[None, :] * (rr * np.cos(ang))[:, None]
                     + e2[None, :] * (rr * np.sin(ang))[:, None])
        V = np.concatenate(V)
        q = ring_faces(2, nseg, True) + b
        allV.append(V)
        allF += [tuple(f) for f in q]
        allF += [tuple(range(b + nseg - 1, b - 1, -1)),
                 tuple(range(b + nseg, b + 2 * nseg))]
    CV = np.concatenate(allV)
    mm = bpy.data.meshes.new("cut")
    mm.from_pydata([tuple(v) for v in CV], [], allF)
    mm.update()
    cob = bpy.data.objects.new("cut", mm)
    bpy.context.scene.collection.objects.link(cob)
    bpy.context.view_layer.objects.active = ob
    m = ob.modifiers.new("punch", "BOOLEAN")
    m.operation = "DIFFERENCE"
    m.object = cob
    m.solver = "EXACT"
    ok = 0
    try:
        bpy.ops.object.modifier_apply(modifier=m.name)
        ok = len(cutters)
    except Exception as e:
        ob.modifiers.remove(m)
        log("WARNING: boolean punch failed on %s (%s); the holes are NOT "
            "there and this post is reported as unpunched." % (ob.name, e))
    bpy.data.objects.remove(cob, do_unlink=True)
    if not ok:
        return 0
    _reattribute(ob, co0, A0, cutters)
    return ok


def _reattribute(ob, co0, A0, cutters):
    """Carry the vertex attributes across a boolean, then mark the bore walls.

    A dict lookup on the quantised position matches the ~99 % of vertices the
    boolean left alone in one pass; only the handful it created need a nearest
    search, and that is done in numpy against the originals rather than through
    a KD tree built one insert at a time.
    """
    me = ob.data
    n1 = len(me.vertices)
    co1 = np.empty(n1 * 3, np.float32)
    me.vertices.foreach_get("co", co1)
    co1 = co1.reshape(-1, 3).astype(np.float64)
    q0 = np.rint(co0 * 1e6).astype(np.int64)
    q1 = np.rint(co1 * 1e6).astype(np.int64)
    tbl = {}
    for i in range(len(q0)):
        tbl[(q0[i, 0], q0[i, 1], q0[i, 2])] = i
    idx = np.full(n1, -1, np.int64)
    for i in range(n1):
        j = tbl.get((q1[i, 0], q1[i, 1], q1[i, 2]), -1)
        idx[i] = j
    miss = np.flatnonzero(idx < 0)
    if len(miss):
        for a0 in range(0, len(miss), 512):
            sel = miss[a0:a0 + 512]
            d = ((co1[sel][:, None, :] - co0[None, :, :]) ** 2).sum(-1)
            idx[sel] = np.argmin(d, axis=1)
    for a in ATTR_F:
        me.attributes[PFX.lower() + a].data.foreach_set(
            "value", A0[a][idx].astype(np.float32))
    bare = A0["bare"][idx].astype(np.float32)
    edg = A0["edge"][idx].astype(np.float32)
    newv = np.zeros(n1, bool)
    newv[miss] = True
    for c in cutters:
        o = np.asarray(c["o"], float)
        a = unit(c["a"])
        d = co1 - o[None, :]
        t = d @ a
        radial = np.linalg.norm(d - np.outer(t, a), axis=1)
        on = (np.abs(radial - c["r"]) < 0.0012) & (t > -0.002) \
            & (t < c["depth"] + 0.002)
        bare = np.where(on, np.maximum(bare, 0.92), bare)
        edg = np.where(on, np.maximum(edg, 0.85), edg)
        near = newv & (np.abs(radial - c["r"]) < 0.004)
        bare = np.where(near, np.maximum(bare, 0.55), bare)
    me.attributes[PFX.lower() + "bare"].data.foreach_set("value", bare)
    me.attributes[PFX.lower() + "edge"].data.foreach_set("value", edg)



def shade_by_angle(me, deg=33.0):
    """Smooth everywhere except across a real arris.  Flat-shading a swept
    fillet turns a 7.6 mm radius into four visible bands 2.7 px wide; sharp
    edges — the toes, the cut ends, the bolt flats, the stamped strokes — stay
    sharp.  Done in numpy because shade_auto_smooth needs a VIEW_3D context and
    cannot run headless."""
    npoly, nloop, nedge = len(me.polygons), len(me.loops), len(me.edges)
    if not nedge or not npoly:
        return
    me.polygons.foreach_set("use_smooth", np.ones(npoly, np.int8))
    fn = np.empty(npoly * 3, np.float32)
    me.polygons.foreach_get("normal", fn)
    fn = fn.reshape(npoly, 3)
    ls = np.empty(npoly, np.int32); me.polygons.foreach_get("loop_start", ls)
    lt = np.empty(npoly, np.int32); me.polygons.foreach_get("loop_total", lt)
    lv = np.empty(nloop, np.int32); me.loops.foreach_get("vertex_index", lv)
    nxt = np.arange(nloop, dtype=np.int64) + 1
    ends = (ls + lt - 1).astype(np.int64)
    nxt[ends] = ls.astype(np.int64)
    a = lv.astype(np.int64)
    b = lv[nxt].astype(np.int64)
    nvert = np.int64(len(me.vertices))
    key = np.minimum(a, b) * nvert + np.maximum(a, b)
    face_of_loop = np.repeat(np.arange(npoly, dtype=np.int64), lt)
    order = np.argsort(key, kind="stable")
    ks, fs = key[order], face_of_loop[order]
    first = np.concatenate([[True], ks[1:] != ks[:-1]])
    grp = np.cumsum(first) - 1
    ng = int(grp[-1]) + 1
    f0 = np.zeros(ng, np.int64)
    f1 = np.full(ng, -1, np.int64)
    np.copyto(f0, fs[np.flatnonzero(first)])
    second = np.flatnonzero(~first)
    if len(second):
        f1[grp[second]] = fs[second]
    dot = np.ones(ng)
    two = f1 >= 0
    if two.any():
        dot[two] = np.einsum("ij,ij->i", fn[f0[two]], fn[f1[two]])
    ang = np.degrees(np.arccos(np.clip(dot, -1.0, 1.0)))
    sharp_key = ks[np.flatnonzero(first)][ang > deg]
    ev = np.empty(nedge * 2, np.int32)
    me.edges.foreach_get("vertices", ev)
    ev = ev.reshape(nedge, 2).astype(np.int64)
    ekey = (np.minimum(ev[:, 0], ev[:, 1]) * nvert
            + np.maximum(ev[:, 0], ev[:, 1]))
    sharp = np.zeros(nedge, np.int8)
    if len(sharp_key):
        sk = np.sort(sharp_key)
        idx = np.clip(np.searchsorted(sk, ekey), 0, len(sk) - 1)
        sharp[sk[idx] == ekey] = 1
    at = me.attributes.get("sharp_edge") or me.attributes.new(
        "sharp_edge", "BOOLEAN", "EDGE")
    at.data.foreach_set("value", sharp)


def place(ob, R, O):
    from mathutils import Matrix
    ob.matrix_world = Matrix(
        ((R[0][0], R[1][0], R[2][0], O[0]),
         (R[0][1], R[1][1], R[2][1], O[1]),
         (R[0][2], R[1][2], R[2][2], O[2]),
         (0.0, 0.0, 0.0, 1.0)))
    return ob


def _object_props(ob, p):
    """Per-object shader inputs.  The offset is what stops 690 posts sharing
    one spangle; it is 24 m and not 240 because Cycles evaluates procedurals in
    float32 and at a Voronoi scale of 300 an offset of 240 puts the lookup
    72 000 cells from the origin, where the mantissa has run out."""
    a = PFX.lower()
    ob[a + "ofs_x"] = float(h01(p.seed, 3) * 24.0)
    ob[a + "ofs_y"] = float(h01(p.seed, 5) * 24.0)
    ob[a + "ofs_z"] = float(h01(p.seed, 7) * 24.0)
    ob[a + "age"] = float(p.galv_age)
    ob[a + "bloom"] = float(p.bloom)
    ob[a + "rust"] = float(p.rust)
    ob[a + "dust"] = float(p.dust)
    ob[a + "mud"] = float(p.mud)
    ob[a + "algae"] = float(p.algae)
    ob[a + "lot"] = float(p.lot)
    ob[a + "capped"] = 1.0 if p.cap_plate else 0.0
    ob[a + "strim"] = float(p.strimmer)
    ob[a + "paint"] = 1.0 if p.paint_band else 0.0
    bn, bh = BRAND_BOOK[p.brand % len(BRAND_BOOK)]
    r, g, b = _srgb(bh)
    ob[a + "band_r"] = r
    ob[a + "band_g"] = g
    ob[a + "band_b"] = b
    ob["item"] = ITEM
    ob["cfp_side"] = int(p.side)
    ob["cfp_pi"] = int(p.pi)
    ob["cfp_s"] = float(p.s)
    ob["cfp_section"] = p.sec.name
    ob["cfp_base_kind"] = p.base_kind
    ob["cfp_lean_deg"] = float(p.lean_deg)
    ob["cfp_tag_no"] = int(p.tag_no)
    ob["cfp_lod"] = int(p.lod)
    ob["cfp_damaged"] = int(bool(p.damaged))
    ob["cfp_brand_band"] = bn


def build_one(p, coll, mats, name=None, lod=None):
    """Emit ONE post as its own object.  Public: grandstand_debris_fence uses
    this against a Post record it makes itself."""
    lod = int(p.lod if lod is None else lod)
    acc, cut = post_acc(p, lod)
    me = acc.to_mesh(name or p.name)
    ob = bpy.data.objects.new(name or p.name, me)
    for m in mats:
        ob.data.materials.append(m)
    coll.objects.link(ob)
    # PUNCH FIRST, PLACE SECOND, AND THAT ORDER IS A DEFECT FIXED.
    # The cutter cylinders are built in the post's LOCAL frame; the Boolean
    # modifier resolves the cutter OBJECT in WORLD space.  With `place()` run
    # first, the post was at (615, 476, -0.9) and its cutters were still sitting
    # at the world origin, so the boolean intersected nothing, removed nothing,
    # raised no error, and every "real drilled hole" in this module was a claim
    # with no geometry behind it.  It survived three builds and two renders
    # because a boolean that cuts nothing looks exactly like one that was never
    # asked to.  `selftest()` now measures the bore.
    n_punched = _punch(ob, cut, lod) if cut else 0
    R, O = p.frame()
    place(ob, R, O)
    shade_by_angle(ob.data, 33.0)
    _object_props(ob, p)
    ob["cfp_holes_punched"] = int(n_punched)
    return ob, acc.stats()


def _grade_lod(posts, anchor):
    """LOD by distance to the nearest camera anchor.  Never a global setting."""
    if not anchor:
        for p in posts:
            p.lod = 1
        return
    A = np.asarray(anchor, float)[:, :2]
    P = np.array([[q.base[0], q.base[1]] for q in posts])
    d = np.sqrt(((P[:, None, :] - A[None, :, :]) ** 2).sum(-1)).min(axis=1)
    for q, dd in zip(posts, d):
        q.lod = 3 if dd <= 9.0 else (2 if dd <= 30.0 else (1 if dd <= 130.0 else 0))


def build(scene=None, lod_anchor=None, limit=None, sides=(+1, -1), coll=None):
    """Emit one object per post.  -> (collection, stats)."""
    t0 = time.time()
    scene = scene or bpy.context.scene
    root = coll or _coll(COLL)
    mats = [mat_galv(), mat_fastener(), mat_conc()]
    posts = []
    for sd in sides:
        posts += post_sites(sd)
    _grade_lod(posts, lod_anchor)
    if limit:
        posts = posts[:limit]
    tri = vert = 0
    nl = {0: 0, 1: 0, 2: 0, 3: 0}
    for i, p in enumerate(posts):
        ob, st = build_one(p, root, mats)
        tri += st["triangles"]
        vert += st["verts"]
        nl[p.lod] += 1
        if (i + 1) % 100 == 0:
            log("  %d/%d posts, %.2f M tris" % (i + 1, len(posts), tri / 1e6))
    stats = dict(posts=len(posts), triangles=tri, verts=vert, lod=nl,
                 seconds=round(time.time() - t0, 1))
    log("built %d posts (%s) %.2f M triangles in %.0f s"
        % (len(posts), " ".join("L%d:%d" % (k, v) for k, v in sorted(nl.items())),
           tri / 1e6, time.time() - t0))
    return root, stats


