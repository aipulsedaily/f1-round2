def contract_light(scene=None, coll=None):
    """The film's sun and sky, exactly as world_contract measured them."""
    from mathutils import Vector
    scene = scene or bpy.context.scene
    w = bpy.data.worlds.new(PFX + "World")
    w.use_nodes = True
    nt = w.node_tree
    nt.nodes.clear()
    out = nt.nodes.new("ShaderNodeOutputWorld")
    bg = nt.nodes.new("ShaderNodeBackground")
    sky = nt.nodes.new("ShaderNodeTexSky")
    avail = {e.identifier for e in sky.bl_rna.properties["sky_type"].enum_items}
    for want in ("MULTIPLE_SCATTERING", "SINGLE_SCATTERING", "HOSEK_WILKIE"):
        if want in avail:
            sky.sky_type = want
            break
    for attr, val in (("sun_disc", False),
                      ("sun_size", math.radians(C.SUN_ANGULAR_DIAM_DEG)),
                      ("sun_intensity", 1.0),
                      ("sun_elevation", math.radians(C.SUN_ELEV_DEG)),
                      ("sun_rotation", math.radians(C.SKY_SUN_ROTATION_DEG)),
                      ("altitude", C.SKY_ALTITUDE),
                      ("air_density", C.SKY_AIR),
                      ("aerosol_density", C.SKY_AEROSOL),
                      ("ozone_density", C.SKY_OZONE)):
        if hasattr(sky, attr):
            setattr(sky, attr, val)
    bg.inputs["Strength"].default_value = 1.0
    nt.links.new(sky.outputs["Color"], bg.inputs["Color"])
    nt.links.new(bg.outputs["Background"], out.inputs["Surface"])
    scene.world = w

    lt = bpy.data.lights.new(PFX + "Sun", "SUN")
    lt.energy = C.SUN_ENERGY
    lt.color = C.SUN_COLOR
    lt.angle = math.radians(C.SUN_ANGULAR_DIAM_DEG)
    ob = bpy.data.objects.new(XPFX + "Sun", lt)
    d = Vector(C.SUN_DIR)
    ob.rotation_mode = "QUATERNION"
    ob.rotation_quaternion = d.to_track_quat("Z", "Y")
    ob.location = (d.x * 2000.0, d.y * 2000.0, d.z * 2000.0)
    ob.visible_camera = False
    (coll or scene.collection).objects.link(ob)
    scene.view_settings.view_transform = C.VIEW_TRANSFORM
    try:
        scene.view_settings.look = C.VIEW_LOOK
    except Exception:
        pass
    scene.view_settings.exposure = C.REFERENCE_EXPOSURE_EXTERIOR
    log("light: sun %.3f W/m2, elev %.2f deg, bearing %.2f deg; AgX %.3f EV"
        % (C.SUN_ENERGY, C.SUN_ELEV_DEG, C.SUN_BEARING_DEG,
           C.REFERENCE_EXPOSURE_EXTERIOR))
    return ob


def add_camera(name, loc, look, lens, coll, fstop=None, roll=0.0):
    from mathutils import Vector, Matrix
    cd = bpy.data.cameras.new(name)
    cd.lens = lens
    cd.sensor_width = SENSOR_MM
    cd.clip_start = 0.01
    cd.clip_end = 20000.0
    ob = bpy.data.objects.new(name, cd)
    ob.location = loc
    d = Vector(look) - Vector(loc)
    ob.rotation_mode = "QUATERNION"
    q = d.to_track_quat("-Z", "Y")
    if roll:
        q = q @ Matrix.Rotation(math.radians(roll), 4, "Z").to_quaternion()
    ob.rotation_quaternion = q
    coll.objects.link(ob)
    if fstop:
        cd.dof.use_dof = True
        cd.dof.focus_distance = float(d.length)
        cd.dof.aperture_fstop = float(fstop)
    return ob


def hero_aim(target_inc=64.0, window=(40.0, 104.0), exclude=(), sides=(-1,),
             avoid_section=None, avoid_base=None):
    """Which post the macro is shot on, and from which side.  By score.

    Six things decide it and none of them is convenience:

      1. RAKING LIGHT ON THE FLANGE.  64 deg of incidence: the face is still
         lit, and every bolt head, weld and zinc run throws its own shadow
         across it.  A post lit face-on is a grey stripe.
      2. IT MUST BE ON THE SIDE THE FILM LOOKS AT.  The doppler hover at
         s = 2555 on side -1 is 4.2 m from these; that neighbourhood scores.
      3. IT MUST HAVE A HISTORY.  Age, bloom and rust are half the score,
         because weathering is half of what this item is judged on and the
         first W-beam macro was shot on a nearly new panel and came back
         reading as clean chrome.
      4. IT MUST NOT BE PLUMB.  Lean is the manifest's own tell.
      5. ITS NEIGHBOURS MUST EXIST, so the shot contains a LINE of posts and
         the variation is visible rather than asserted.
      6. IT SHOULD CARRY SOMETHING UNUSUAL — a stay, a splice, a kink, a
         plated base.  Not all of them; one of them.
    """
    sun = np.array(C.SUN_DIR, float)
    cand = []
    for sd in sides:
        ps = post_sites(sd)
        by = {p.pi: p for p in ps}
        for p in ps:
            R, O = p.frame()
            nbr = sum(1 for k in (-2, -1, 1, 2) if (p.pi + k) in by)
            # THE CAMERA IS ALWAYS OUTBOARD, and this is not a preference.
            # The mesh panel bears on the TRACK-side flange, so a camera on
            # that side is looking through somebody else's fabric at my post:
            # the first macro came back as 94 % stand-in weave with the hero
            # post cropped at the frame edge.  Outboard is also where the film
            # actually stands -- the doppler hover is on the verge, 4.2 m out,
            # looking past the fence -- and it is the side that carries the
            # nuts, the thread stick-out, the web, the rolled-in mill mark, the
            # stay and the base plate.
            s = 1.0
            face = R @ (np.array([0.0, s, 0.0]))
            inc = math.degrees(math.acos(float(np.clip(np.dot(face, sun),
                                                       -1.0, 1.0))))
            ds = abs(((p.s - 2555.0 + C.LAP * 0.5) % C.LAP) - C.LAP * 0.5)
            score = (150.0 * (0.30 * p.galv_age + 0.42 * p.bloom
                              + 0.28 * p.rust)
                     + 46.0 * min(abs(p.lean_deg) / 2.2, 1.0)
                     + 30.0 * nbr
                     + 40.0 * (1.0 if p.raker else 0.0)
                     + 34.0 * (1.0 if p.damaged else 0.0)
                     + 26.0 * (1.0 if p.splice_z else 0.0)
                     + 22.0 * (1.0 if p.base_kind == "plate" else 0.0)
                     + 20.0 * min(len(p.spare_holes), 3)
                     + 26.0 * (1.0 if p.paint_band else 0.0)
                     + 50.0 * max(0.0, 1.0 - ds / 420.0)
                     # THE SECOND MACRO MUST NOT BE THE FIRST ONE AGAIN.  Posts
                     # are erected in batches and a batch shares a section, so
                     # the two best-scoring posts are usually neighbours of the
                     # same rolled size on the same kind of base -- and a pair
                     # of macros that both show a 152x152x30 UC on a base plate
                     # is not evidence of variation, it is evidence of one post
                     # photographed twice.
                     - (260.0 if (avoid_section and p.sec.name == avoid_section)
                        else 0.0)
                     - (90.0 if (avoid_base and p.base_kind == avoid_base)
                        else 0.0)
                     - 2.4 * abs(inc - target_inc))
            cand.append((score, p, inc, s, nbr))
    lit = [c for c in cand if window[0] <= c[2] <= window[1]]
    pool = lit if lit else cand
    pool.sort(key=lambda c: -c[0])
    for sc, p, inc, s, nbr in pool:
        if (p.side, p.pi) in exclude:
            continue
        return dict(post=p, sun_incidence_deg=inc, side_sign=s, score=sc,
                    neighbours=nbr, n_lit=len(lit), n_cand=len(cand))
    raise RuntimeError("no hero post found")


def macro_rig(aim, cams, name, yaw_deg=13.0, elev_deg=5.0, height=1.00,
              lens=None, dist=None, fstop=3.5):
    """A camera at EXACTLY nearest_camera_m on lens_at_closest_mm.

    2.600 m is the NEAREST the lens ever gets, so the camera sits on the
    perpendicular through the aim point at exactly 2.600 m and is then ROTATED,
    not moved, to compose.  Moving it to get the angle would bring the post
    inside 2.600 m, and the manifest already says the post overfills the frame
    at that distance.

    THE YAW IS 13 deg AND THAT NUMBER IS ARITHMETIC, NOT TASTE.  Half the
    horizontal field on a 35 mm lens is atan(18/35) = 27.2 deg, so a yaw of y
    puts the subject at y / 27.2 of the way from the centre to the edge.  The
    first version used 26 deg, which is 96 % of the way out: the hero post was
    cropped by the frame edge and the shot was of the background.  13 deg puts
    it at 48 %, i.e. a quarter of the way in from the left, with the receding
    line of posts filling the rest -- which is the whole variation argument in
    one frame.

    THE FRAME IS AIMED LOW ON PURPOSE.  1.504 m of subject height fits at this
    distance and the interesting 1.5 m of a fence post is the BOTTOM 1.5 m: the
    base, the ground line, the splash band, the strimmer scar, two clamp bars
    and the number tag.  The first pass centred on 1.30 m and spent half the
    frame on plain section.

    f/3.5 is also arithmetic.  The mesh panel bears on the post 0.16 m away, so
    it is unavoidably in shot and it is SOMEBODY ELSE'S ITEM; at f/3.5 the
    depth of field is 2.28-3.03 m, which keeps the near bay sharp and lets the
    run behind it go soft instead of competing with the thing being judged.
    """
    p = aim["post"]
    s = float(aim.get("side_sign", 1.0))
    R, O = p.frame()
    Cc, eu, ev = post_frames(p, np.array([height]))
    # AZIMUTH.  Standing on the perpendicular to a flange gives a 153 mm plate
    # seen face-on, which renders as a featureless bar -- the 4K macro came
    # back with the post reading as a smooth tube.  Swinging 34 deg round the
    # axis shows the flange AND the toe AND a slice of the web, which is what
    # makes an H section legible as an H section.
    #
    # The distance stays EXACTLY the manifest's 2.600 m because it is measured
    # to the NEAREST POINT OF THE STEEL, not to a nominal face: the section's
    # support distance in the camera's own direction is computed from the
    # profile and added to 2.600.  Anything else either cheats the number or
    # quietly films the item from 2.68 m and calls it 2.6.
    az = math.radians(float(aim.get("azimuth_deg", 34.0)))
    dloc = np.array([math.sin(az) * s, math.cos(az) * s])
    P2 = section_loops(p.sec, 3)[0][0]
    support = float(np.max(P2 @ dloc))
    d = float(dist if dist is not None else FILMED_AT_M)
    lm = float(lens if lens is not None else LENS_MM)
    dirw = R @ (eu[0] * dloc[0] + ev[0] * dloc[1])
    axis_pt = O + R @ Cc[0]
    surf = axis_pt + dirw * support
    along = R @ eu[0]
    el = math.radians(elev_deg)
    off = unit(dirw * math.cos(el) + np.array([0.0, 0.0, 1.0]) * math.sin(el))
    cam_p = surf + off * d
    look = surf + along * (d * math.tan(math.radians(yaw_deg)))
    cam = add_camera(name, tuple(cam_p), tuple(look), lm, cams, fstop=fstop)
    # MEASURE what was built, do not assert it: the closest vertex of the
    # section outline to the camera, in metres.
    ring = axis_pt[None, :] + (R @ np.stack([eu[0], ev[0]], axis=1)
                               @ P2.T).T
    dd = float(np.min(np.linalg.norm(ring - cam_p[None, :], axis=1)))
    fw = dd * SENSOR_MM / lm
    fh = fw * 2160.0 / 3840.0
    log("%s: MEASURED %.4f m to the nearest steel on a %.1f mm lens "
        "(manifest %.1f m / %.0f mm), azimuth %.0f deg off the flange normal"
        % (name, dd, lm, FILMED_AT_M, LENS_MM, math.degrees(az)))
    log("   post %s pi=%d  s=%.1f  %s  lean %+.2f deg  sun incidence %.1f deg"
        % ("L" if p.side > 0 else "R", p.pi, p.s, p.sec.name, p.lean_deg,
           aim["sun_incidence_deg"]))
    log("   base=%s cleats=%d raker=%s damaged=%s splice=%s spare_holes=%d "
        "tag=%d" % (p.base_kind, p.n_cleat, p.raker, p.damaged,
                    bool(p.splice_z), len(p.spare_holes), p.tag_no))
    log("   frame %.3f x %.3f m; the %.3f m section reads %.0f px of 3840, "
        "the post height %.0f px of 2160 (manifest %.0f, overfills)"
        % (fw, fh, p.sec.D, p.sec.D / fw * 3840.0, p.stand_h / fh * 2160.0,
           ONSCREEN_PX_4K))
    return cam, cam_p, surf


# ------------------------------------------------------------------ stand-ins
#
# The macro has to be judged in context, so the acceptance scene carries the
# ground the posts stand in and CRUDE proxies for three items that are not
# mine: catch_fence_mesh_panel, catch_fence_base_collar and armco_w_beam's
# guardrail.  They are prefixed CFPSTAND_ so `--prefix CFP_` cannot count
# them: measuring my own item's triangles and then including someone else's
# stand-ins would answer a different question than the one asked.

def mat_standin(name, base, rough=0.75, scale=30.0, bumpstr=0.25):
    nm = XPFX + name
    if nm in bpy.data.materials:
        return bpy.data.materials[nm]
    t = NT(nm)
    co = t.n("ShaderNodeTexCoord")
    P = (co, 3)
    n1_ = t.noise(P, scale, 8.0, 0.6)
    n2_ = t.noise(t.vmath("SCALE", P, scale=3.0), scale * 7.0, 5.0, 0.6)
    col = t.cmix(t.maprange(n1_, 0.3, 0.7, 0.0, 0.45), base,
                 tuple(c * 0.55 for c in base))
    col = t.cmix(t.maprange(n2_, 0.35, 0.75, 0.0, 0.30), col,
                 tuple(c * 1.35 for c in base))
    rg = t.fmix(t.maprange(n1_, 0.2, 0.8, 0.0, 1.0), rough, min(0.99, rough + 0.12))
    b = t.bump(n2_, bumpstr, 0.002)
    bs = t.n("ShaderNodeBsdfPrincipled")
    t.pin(bs, 0, col)
    t.pin(bs, bs.inputs.find("Roughness"), rg)
    t.pin(bs, bs.inputs.find("Normal"), b)
    o = t.n("ShaderNodeOutputMaterial")
    t.t.links.new(bs.outputs[0], o.inputs["Surface"])
    return t.m


def build_ground(coll, centre, half=30.0, cell=0.055, name="Ground"):
    """The maintenance strip the post stands in.

    A FLAT PLANE HERE IS A LIE THAT LANDS ON MY ITEM.  It fills the bottom
    third of the macro; the first render came back with the post standing on
    a beige void, which is exactly the "grass gray line" the user rejected.
    The real surface belongs to build_barriers, so this is only a stand-in —
    but a stand-in with 55 mm cells and real displacement, because at a 12.5
    deg sun a 12 mm rut throws a 54 mm shadow and that is what a ground plane
    is made of at 2.6 m.
    """
    n = int(2 * half / cell) + 1
    g = np.linspace(-half, half, n)
    X, Y = np.meshgrid(g + centre[0], g + centre[1], indexing="ij")
    Z, own = C.world_ground_z(X.ravel(), Y.ravel())
    Z = np.where(np.isfinite(Z), Z, 0.0)
    xr = X.ravel() - centre[0]
    yr = Y.ravel() - centre[1]
    # graded fill: 90 mm ruts and hollows, 22 mm clods, 6 mm grit
    Z = (Z
         + 0.045 * (fbm1(xr * 0.55, seed=11, oct=3)
                    + fbm1(yr * 0.55, seed=17, oct=3) - 1.0)
         + 0.014 * (fbm1(xr * 3.1 + yr * 1.7, seed=23, oct=4) - 0.5)
         + 0.006 * (fbm1(xr * 13.0 - yr * 9.0, seed=29, oct=3) - 0.5)
         + 0.0025 * (fbm1(xr * 47.0 + yr * 41.0, seed=31, oct=2) - 0.5))
    V = np.stack([X.ravel(), Y.ravel(), Z], 1)
    me = bpy.data.meshes.new(XPFX + name)
    me.from_pydata([tuple(v) for v in V], [],
                   [tuple(q) for q in grid_quads(n, n)])
    me.update()
    shade_by_angle(me, 46.0)
    ob = bpy.data.objects.new(XPFX + name, me)
    ob.data.materials.append(mat_standin("Verge", (0.086, 0.079, 0.058),
                                         0.92, 34.0, 0.85))
    coll.objects.link(ob)
    return ob


def build_far_ground(coll, centre, half=900.0, cell=25.0):
    """Blender's Sky Texture returns BLACK below the horizon, so a finite
    ground patch renders as a hard black band behind the fence — an artefact of
    the test scene that would be read as a defect in the item."""
    n = int(2 * half / cell) + 1
    g = np.linspace(-half, half, n)
    X, Y = np.meshgrid(g + centre[0], g + centre[1], indexing="ij")
    Z, own = C.world_ground_z(X.ravel(), Y.ravel())
    fin = np.isfinite(Z)
    xr = X.ravel() - centre[0]
    yr = Y.ravel() - centre[1]
    # Outside the road platform the contract returns NaN because terrain owns
    # the ground.  Flattening that to z = 0 draws a razor-straight horizon
    # across the back of every frame; a 1.8 m roll over 300 m does not.
    far = (1.8 * (fbm1(xr * 0.0042, seed=41, oct=4)
                  + fbm1(yr * 0.0038, seed=43, oct=4) - 1.0)
           + 0.45 * (fbm1(xr * 0.021 + yr * 0.017, seed=47, oct=3) - 0.5))
    Z = np.where(fin, Z, far) - 0.006
    V = np.stack([X.ravel(), Y.ravel(), Z], 1)
    me = bpy.data.meshes.new(XPFX + "FarGround")
    me.from_pydata([tuple(v) for v in V], [],
                   [tuple(q) for q in grid_quads(n, n)])
    me.update()
    ob = bpy.data.objects.new(XPFX + "FarGround", me)
    ob.data.materials.append(mat_standin("Far", (0.115, 0.118, 0.092),
                                         0.92, 1.1, 0.10))
    coll.objects.link(ob)
    return ob


def build_standins(coll, anchor, near_m=40.0, sides=(-1,)):
    """Proxy fabric, collars and guardrail so the macro reads as a real fence.

    The FABRIC matters most: the clamp bars grip it, and a bar clamping air is
    a broken photograph.  It is deliberately a crude weave — the real one is
    catch_fence_mesh_panel's job and this must not be mistaken for it.
    """
    A = np.asarray(anchor, float)[:, :2]
    mgalv = mat_standin("Galv2", (0.150, 0.154, 0.160), 0.45, 90.0, 0.30)
    mconc = mat_standin("Pier", (0.145, 0.142, 0.134), 0.88, 26.0, 0.45)
    acc = Acc(XPFX + "Fabric")
    nsp = 0
    for sp in spans(None if len(sides) > 1 else sides[0]):
        a = np.array(sp["face_a"], float)
        b = np.array(sp["face_b"], float)
        mid = 0.5 * (a + b)
        if np.sqrt(((mid[:2][None, :] - A) ** 2).sum(-1)).min() > near_m:
            continue
        d = b - a
        Lb = float(np.linalg.norm(d))
        if Lb < 1e-3:
            continue
        ex = d / Lb
        ez = np.array([0.0, 0.0, 1.0])
        ey = unit(np.cross(ez, ex))
        z0 = sp["mesh_bottom"]
        z1 = min(sp["mesh_top"], z0 + MESH_H)
        pitch = 0.050
        wr = 0.0025
        nv = int(Lb / pitch)
        nh = int((z1 - z0) / pitch)
        # A PERFECT GRID IS THE MOST CG THING IN THE FRAME, and this stand-in
        # sits 0.16 m behind the item being judged.  Every bay gets its own
        # tension state and every wire its own wander, so the proxy does not
        # itself become the failure the real panel item exists to avoid.
        sd = 4400 + int(sp["pi"]) * 17 + (1 if sp["side"] > 0 else 0)
        belly = 0.018 + 0.055 * h01(sd, 3)
        drop = 0.004 + 0.022 * h01(sd, 5)
        for i in range(nv):
            x = (i + 0.5) * pitch + (h01(sd, 100 + i) - 0.5) * 0.005
            u01 = x / max(Lb, 1e-6)
            sag = belly * math.sin(math.pi * u01) ** 1.3
            p0 = a + ex * x + ez * (z0 - drop * math.sin(math.pi * u01))
            p1 = a + ex * x + ez * z1
            path = np.stack([p0 + ey * 0.0012,
                             0.65 * p0 + 0.35 * p1 + ey * (0.002 + sag * 0.7),
                             0.30 * p0 + 0.70 * p1 + ey * (0.002 + sag),
                             p1 + ey * 0.0012])
            pr, _ = circle(5, wr * (0.94 + 0.13 * h01(sd, 300 + i)))
            sweep_ring(acc, path, pr, mat=0, caps=(False, False))
        for j in range(nh):
            zz = z0 + (j + 0.5) * pitch + (h01(sd, 500 + j) - 0.5) * 0.005
            v01 = (zz - z0) / max(z1 - z0, 1e-6)
            s2 = belly * math.sin(math.pi * v01) ** 0.8
            p0 = a + ez * zz
            p1 = b + ez * zz
            path = np.stack([p0 + ey * 0.0055,
                             0.5 * (p0 + p1) + ey * (0.019 + s2),
                             p1 + ey * 0.0055])
            pr, _ = circle(5, wr * (0.94 + 0.13 * h01(sd, 700 + j)))
            sweep_ring(acc, path, pr, mat=0, caps=(False, False))
        nsp += 1
    if nsp:
        me = acc.to_mesh(XPFX + "Fabric")
        ob = bpy.data.objects.new(XPFX + "Fabric", me)
        ob.data.materials.append(mgalv)
        shade_by_angle(me, 40.0)
        coll.objects.link(ob)
    # --- collars ------------------------------------------------------------
    acc = Acc(XPFX + "Collars")
    nc = 0
    for cs in collar_sites(None if len(sides) > 1 else sides[0]):
        w = np.array(cs["world"], float)
        if np.sqrt(((w[:2][None, :] - A) ** 2).sum(-1)).min() > near_m:
            continue
        if cs["base_kind"] == "driven":
            continue
        r = cs["pier_d"] * 0.5
        top = cs["ground_z"] + cs["pier_top"]
        ring, _ = circle(18, r)
        V = []
        for zz in (top - 0.30, top - 0.012, top):
            rr = ring * (1.0 if zz < top - 0.02 else 0.96)
            V.append(np.stack([w[0] + rr[:, 0], w[1] + rr[:, 1],
                               np.full(18, zz)], axis=1))
        V.append(np.array([[w[0], w[1], top]]))
        V = np.concatenate(V)
        q = ring_faces(3, 18, True)
        tr = fan(54, np.arange(36, 54))
        acc.solid(V, quads=q, tris=tr, mat=0)
        nc += 1
    if nc:
        me = acc.to_mesh(XPFX + "Collars")
        ob = bpy.data.objects.new(XPFX + "Collars", me)
        ob.data.materials.append(mconc)
        shade_by_angle(me, 34.0)
        coll.objects.link(ob)
    # --- guardrail ----------------------------------------------------------
    acc = Acc(XPFX + "Armco")
    nr = 0
    for sd in sides:
        ln = barrier_line(sd)
        L, P = ln["L"], ln["P"]
        u = np.arange(0.0, ln["total"], 1.0)
        pts = np.stack([np.interp(u, L, P[:, k]) for k in range(3)], axis=1)
        keep = np.sqrt(((pts[:, None, :2] - A[None, :, :]) ** 2).sum(-1)).min(1) \
            < near_m + 12.0
        idx = np.flatnonzero(keep)
        if len(idx) < 3:
            continue
        for a0, b0 in _runs(idx):
            seg = pts[a0:b0 + 1]
            if len(seg) < 3:
                continue
            # EXPLICIT FRAMES.  Parallel transport is right for a tube and
            # wrong for a beam: it let the W section roll about the path, and
            # the first wide render showed the guardrail lying FLAT on the
            # ground as a row of yellow chevrons.  A W-beam's section is
            # horizontal-across and vertical-up, always.
            d = np.gradient(seg, axis=0)
            d[:, 2] = 0.0
            d /= np.maximum(np.linalg.norm(d, axis=1)[:, None], 1e-9)
            rt = np.stack([d[:, 1], -d[:, 0], np.zeros(len(d))], axis=1)
            up = np.tile(np.array([0.0, 0.0, 1.0]), (len(d), 1))
            # (across, up) of the EN 1317 profile A section, in metres
            pr = np.array([[0.0, -0.156], [0.083, -0.100], [0.028, -0.030],
                           [0.083, 0.030], [0.083, 0.100], [0.0, 0.156]])
            for hgt in (0.700, 0.386, 0.072):
                base = seg + np.array([0.0, 0.0, hgt + 0.156])
                V = (base[:, None, :] + rt[:, None, :] * pr[None, :, 0, None]
                     + up[:, None, :] * pr[None, :, 1, None])
                acc.add(V.reshape(-1, 3),
                        quads=ring_faces(len(base), len(pr), closed=False),
                        mat=0)
            nr += 1
    if nr:
        me = acc.to_mesh(XPFX + "Armco")
        ob = bpy.data.objects.new(XPFX + "Armco", me)
        ob.data.materials.append(mgalv)
        shade_by_angle(me, 34.0)
        coll.objects.link(ob)
    log("stand-ins: %d fabric bays, %d collars, %d guardrail runs within %.0f m"
        % (nsp, nc, nr, near_m))


def _runs(idx):
    out, a = [], idx[0]
    for i in range(1, len(idx)):
        if idx[i] != idx[i - 1] + 1:
            out.append((a, idx[i - 1]))
            a = idx[i]
    out.append((a, idx[-1]))
    return out


