def mat_galv():
    """ONE material for the post: section, cleats, welds, tag, mark.

    THIRTEEN histories, in the order the steel acquired them:

        mill scale under the zinc, rolled in
          -> the DIP: dendritic spangle whose crystal size is a property of the
             SECTION, because a 6.5 mm web freezes 4-12 mm crystals and a
             16 mm base plate holds its heat and grows 12-30 mm ones
          -> zinc runs and dross where it drained, keyed to real geometry
          -> carbonate bloom (wet-storage stain) in the root fillets, inside
             the section and in the splash zone first
          -> weathering: the blue-grey goes matte grey goes dark
          -> red rust out of every drilled hole, cut end and stamped stroke
          -> rust RUNNING DOWN from those, and out of an uncapped section
          -> track film: rubber and brake dust, heavier low and on the track
             side, because that is the side the car throws it at
          -> paddock dust on every upward-facing surface
          -> mud thrown at the bottom 400 mm
          -> rain wash cutting clean streaks back through all of it
          -> the strimmer scar: bright bare steel in a band at 60-160 mm, which
             is the single most recognisable thing about a real fence post
          -> algae at the base on the side the sun never reaches
          -> a contractor's paint band on 11 % of them

    TWO COORDINATE STREAMS.  `OBJ` is the post's own frame, origin at its base
    point, |P| < 5 m — TexCoord -> Object, never Geometry -> Position.  `NZ` is
    the same plus a per-object offset and it is what every noise reads, so 690
    posts do not share one spangle.  Anything that depends on HEIGHT reads the
    baked `cfp_hz` attribute instead, because a leaning post's local z is not
    its height above the ground and a world z is not available at this
    precision.
    """
    name = PFX + "Galv"
    if name in bpy.data.materials:
        return bpy.data.materials[name]
    t = NT(name)
    A = PFX.lower()
    co = t.n("ShaderNodeTexCoord")
    OBJ = (co, 3)                                   # Object — NEVER Position

    ofs = t.comb(t.attr(A + "ofs_x", 2, "OBJECT"),
                 t.attr(A + "ofs_y", 2, "OBJECT"),
                 t.attr(A + "ofs_z", 2, "OBJECT"))
    NZ = t.vmath("ADD", OBJ, ofs)

    kind = t.attr(A + "kind")
    arc = t.attr(A + "arc")
    ang = t.attr(A + "ang")
    hz = t.attr(A + "hz")
    expo = t.attr(A + "expo")
    crev = t.attr(A + "crev")
    edgev = t.attr(A + "edge")
    weldv = t.attr(A + "weldv")
    barev = t.attr(A + "bare")
    dripv = t.attr(A + "drip")
    dentv = t.attr(A + "dent")

    age = t.attr(A + "age", 2, "OBJECT")
    bloom_o = t.attr(A + "bloom", 2, "OBJECT")
    rust_o = t.attr(A + "rust", 2, "OBJECT")
    dust_o = t.attr(A + "dust", 2, "OBJECT")
    mud_o = t.attr(A + "mud", 2, "OBJECT")
    algae_o = t.attr(A + "algae", 2, "OBJECT")
    lot = t.attr(A + "lot", 2, "OBJECT")
    capped = t.attr(A + "capped", 2, "OBJECT")
    strim = t.attr(A + "strim", 2, "OBJECT")
    paint = t.attr(A + "paint", 2, "OBJECT")
    band = t.comb(t.attr(A + "band_r", 2, "OBJECT"),
                  t.attr(A + "band_g", 2, "OBJECT"),
                  t.attr(A + "band_b", 2, "OBJECT"))

    up = t.sep(t.geo(1), 2)                          # world normal z
    upm = t.maprange(up, 0.05, 0.80, 0.0, 1.0)
    downm = t.maprange(up, -0.10, -0.80, 0.0, 1.0)

    is_weld = t.maprange(weldv, 0.2, 0.8, 0.0, 1.0)
    is_plate = t.maprange(kind, 4.5, 5.5, 0.0, 1.0)

    # ------------------------------------------------------------ 1. THE DIP
    # Dendritic spangle.  Crystal size comes from the DIP LOT and from the
    # thickness of what was dipped: thin webs freeze small, heavy plate grows
    # big.  6-28 mm is 9-40 px here and it is the single most identifying
    # feature of galvanised steel at this distance.
    sc = t.fmix(is_plate, t.maprange(lot, 0.0, 2.0, 78.0, 165.0),
                t.maprange(lot, 0.0, 2.0, 42.0, 96.0))
    spang = t.vor(NZ, sc, "F1", 1, 0.98)
    cellv = t.sep(spang, 0)
    # THE FACET.  A spangle is not a pattern printed on flat metal, it is a
    # MOSAIC OF TINY MIRRORS: each zinc crystal froze at its own orientation
    # and reflects a different part of the sky.  Colour alone gave a surface
    # that read as sandstone under a warm low sun -- the first CLEAT macro came
    # back beige.  h = (P - cell centre) . (cell random) is a LINEAR ramp inside
    # each cell and therefore a constant gradient, i.e. a flat facet at a random
    # tilt, and 2.8 deg of it is the whole difference between zinc and stone.
    vpos = t.vor(NZ, sc, "F1", 2, 0.98)
    facet_h = t.math("MULTIPLY",
                     t.dot(t.vmath("SUBTRACT", NZ, vpos),
                           t.vmath("SUBTRACT", spang, (0.5, 0.5, 0.5))), 25.0)
    edgeD = t.vor(NZ, sc, "DISTANCE_TO_EDGE", 0, 0.98)
    edgem = t.maprange(edgeD, 0.0, 0.075, 1.0, 0.0)
    dend = t.noise(t.vmath("SCALE", t.vmath("ADD", NZ,
                                            t.vmath("SCALE", spang, scale=0.30)),
                           scale=4.6), 210.0, 7.0, 0.74, dist=1.5)
    fine = t.noise(NZ, 780.0, 3.0, 0.5)

    zinc = t.cmix(t.maprange(cellv, 0.06, 0.94, 0.0, 1.0),
                  PAL["zinc_dull"], PAL["zinc_fresh"])
    zinc = t.cmix(t.maprange(dend, 0.30, 0.74, 0.0, 0.92), zinc, PAL["zinc_dark"])
    zinc = t.cmix(t.math("MULTIPLY", edgem, 0.52), zinc, PAL["zinc_dark"])
    zinc = t.cmix(t.maprange(fine, 0.30, 0.70, 0.0, 0.26), zinc, PAL["zinc_dark"])
    # a fresh dip is blue-grey; it loses that in the first year
    zinc = t.cmix(t.maprange(age, 0.35, 0.02, 0.0, 0.55), zinc, PAL["zinc_blue"])
    # ... and an OLD one goes matte dark grey.  This is the single biggest
    # per-post read at 20-40 m: the first wide render had 668 posts of exactly
    # one tone, because `age` only ever removed the blue and never added the
    # grey.  A fence built over twenty years is not one colour.
    zinc = t.cmix(t.maprange(age, 0.18, 1.0, 0.0, 0.62), zinc,
                  t.cmix(0.45, PAL["zinc_dull"], PAL["zinc_dark"]))

    # mill scale striations ALONG the member: `arc` is metres, so 900 bands/m
    # is a 1.1 mm pitch = 1.6 px, right at the resolving limit, which is where
    # a rolled surface's texture actually lives.
    # `ang` is 0..1 ONCE round the section, whose perimeter is 0.93 m, so a
    # Wave scale of 620 is a 1.5 mm pitch = 2.2 px.  The first version used 52,
    # an 18 mm pitch, which is not a mill striation, it is a corrugation.
    roll = t.wave(t.comb(t.math("MULTIPLY", ang, 1.0),
                         t.math("MULTIPLY", arc, 0.11), 0.0), 620.0, 2.4, 4.0)
    zinc = t.cmix(t.maprange(roll, 0.18, 0.82, 0.0, 0.24), zinc, PAL["zinc_dark"])

    # zinc runs: where the geometry already bulges, the metal is thicker,
    # duller and full of dross
    dross = t.noise(t.vmath("SCALE", NZ, scale=3.2), 620.0, 6.0, 0.80)
    zinc = t.cmix(t.math("MULTIPLY", dripv, 0.62), zinc,
                  t.cmix(t.maprange(dross, 0.35, 0.72, 0.0, 1.0),
                         PAL["zinc_dull"], PAL["zinc_dark"]))

    # ------------------------------------------------- 2. CARBONATE BLOOM
    # White rust is a BLOTCH and it grows where water SITS: root fillets, the
    # inside of the section, under the cleat bars, and the bottom 500 mm.
    wet = t.math("ADD", t.math("MULTIPLY", crev, 0.85),
                 t.math("MULTIPLY", upm, 0.38), clamp=True)
    wet = t.math("ADD", wet, t.maprange(hz, 0.55, 0.02, 0.0, 0.50), clamp=True)
    wet = t.math("ADD", wet, t.math("MULTIPLY", is_weld, 0.45), clamp=True)
    blot = t.noise(t.vmath("SCALE", NZ, scale=1.0), 6.8, 9.0, 0.70)
    blot2 = t.noise(t.vmath("SCALE", NZ, scale=2.7), 22.0, 7.0, 0.62)
    bl = t.math("MULTIPLY", t.maprange(blot, 0.38, 0.72, 0.0, 1.0),
                t.maprange(blot2, 0.30, 0.78, 0.25, 1.0))
    bl = t.math("MULTIPLY", bl, t.math("MULTIPLY", bloom_o, wet))
    zinc = t.cmix(t.maprange(bl, 0.03, 0.62, 0.0, 0.92), zinc, PAL["white_rust"])

    # ------------------------------------------------------- 3. RED RUST
    # Zinc protects steel sacrificially, so rust only starts where the coat is
    # GONE: a drilled hole, a sheared end, a stamped stroke, a stone chip, a
    # strimmer.  `bare` is baked by the geometry that made those.
    chip = t.noise(t.vmath("SCALE", NZ, scale=1.0), 165.0, 8.0, 0.72)
    chipm = t.math("MULTIPLY", t.maprange(chip, 0.62, 0.80, 0.0, 1.0),
                   t.maprange(edgev, 0.15, 0.95, 0.05, 1.0))
    barem = t.math("ADD", barev, t.math("MULTIPLY", chipm,
                                        t.maprange(age, 0.0, 1.0, 0.20, 0.95)),
                   clamp=True)
    # the strimmer scar: a hard band at 60-160 mm, and it is bright bare steel
    strimb = t.math("MULTIPLY",
                    t.math("MULTIPLY", t.maprange(hz, 0.045, 0.075, 0.0, 1.0),
                           t.maprange(hz, 0.185, 0.150, 0.0, 1.0)),
                    t.math("MULTIPLY", strim, t.maprange(expo, 0.25, 0.9,
                                                         0.25, 1.0)))
    strimn = t.noise(t.vmath("SCALE", NZ, scale=8.0), 240.0, 5.0, 0.6)
    strimb = t.math("MULTIPLY", strimb, t.maprange(strimn, 0.30, 0.66, 0.15, 1.0))
    barem = t.math("ADD", barem, strimb, clamp=True)
    zinc = t.cmix(t.math("MULTIPLY", barem, 0.85), zinc, PAL["steel_bare"])

    rustn = t.noise(t.vmath("SCALE", NZ, scale=1.0), 58.0, 9.0, 0.74)
    rustn2 = t.noise(t.vmath("SCALE", NZ, scale=4.4), 340.0, 6.0, 0.68)
    rustm = t.math("MULTIPLY", barem, t.math("MULTIPLY", rust_o,
                                             t.maprange(rustn, 0.30, 0.78,
                                                        0.15, 1.0)))
    rustc = t.cmix(t.maprange(rustn2, 0.32, 0.74, 0.0, 1.0),
                   PAL["rust_dark"], PAL["rust_bright"])
    rustc = t.cmix(t.maprange(rustn, 0.40, 0.70, 0.0, 0.7), rustc, PAL["red_rust"])
    zinc = t.cmix(t.maprange(rustm, 0.02, 0.55, 0.0, 1.0), zinc, rustc)

    # rust RUNNING DOWN.  Vertical streaks below every bare place, and out of
    # the open top of an uncapped section — which is why `capped` is a property.
    strk = t.wave(t.comb(t.math("MULTIPLY", ang, 46.0),
                         t.math("MULTIPLY", hz, 0.34), 0.0), 1.0, 3.4, 6.0)
    strkn = t.noise(t.comb(t.math("MULTIPLY", ang, 30.0),
                           t.math("MULTIPLY", hz, 1.1), 0.0), 26.0, 8.0, 0.7)
    run = t.math("MULTIPLY", t.maprange(strk, 0.35, 0.85, 0.0, 1.0),
                 t.maprange(strkn, 0.34, 0.76, 0.0, 1.0))
    topbleed = t.math("MULTIPLY", t.maprange(capped, 1.0, 0.0, 0.0, 1.0),
                      t.maprange(hz, 4.80, 3.40, 1.0, 0.0))
    run = t.math("MULTIPLY", run,
                 t.math("ADD", topbleed,
                        t.math("MULTIPLY", rust_o,
                               t.maprange(expo, 0.2, 0.95, 0.15, 1.0)),
                        clamp=True))
    zinc = t.cmix(t.maprange(run, 0.10, 0.62, 0.0, 0.66), zinc,
                  t.cmix(0.45, PAL["red_rust"], PAL["rust_dark"]))

    # ------------------------------------------- 4. WHAT THE CIRCUIT PUT ON IT
    # Rubber and brake dust arrive from ONE side: the track.  `expo` is 1 on
    # the outboard faces and 0 on the track faces, so the film is keyed to
    # 1 - expo and the post is dirtier on the side the car passes.
    trackside = t.maprange(expo, 0.85, 0.15, 0.0, 1.0)
    filmh = t.maprange(hz, 2.60, 0.10, 0.15, 1.0)
    filmn = t.noise(t.vmath("SCALE", NZ, scale=1.6), 15.0, 8.0, 0.66)
    film = t.math("MULTIPLY", t.math("MULTIPLY", trackside, filmh),
                  t.maprange(filmn, 0.28, 0.76, 0.20, 1.0))
    zinc = t.cmix(t.math("MULTIPLY", film, 0.62), zinc, PAL["rubber"])

    dustn = t.noise(t.vmath("SCALE", NZ, scale=1.3), 34.0, 7.0, 0.62)
    dustm = t.math("MULTIPLY", t.math("MULTIPLY", upm, dust_o),
                   t.maprange(dustn, 0.25, 0.80, 0.30, 1.0))
    dustm = t.math("ADD", dustm, t.math("MULTIPLY", crev,
                                        t.math("MULTIPLY", dust_o, 0.45)),
                   clamp=True)
    zinc = t.cmix(t.maprange(dustm, 0.05, 0.70, 0.0, 0.60), zinc, PAL["dust"])

    mudh = t.maprange(hz, 0.62, 0.02, 0.0, 1.0)
    mudn = t.noise(t.vmath("SCALE", NZ, scale=3.0), 78.0, 8.0, 0.72)
    mudm = t.math("MULTIPLY", t.math("MULTIPLY", mudh, mud_o),
                  t.maprange(mudn, 0.34, 0.76, 0.0, 1.0))
    # a hard splash line at 120-260 mm: every vehicle that has passed in the
    # wet threw the verge at the bottom of this post and it dried there
    splash = t.math("MULTIPLY",
                    t.math("MULTIPLY", t.maprange(hz, 0.02, 0.09, 0.35, 1.0),
                           t.maprange(hz, 0.34, 0.17, 0.0, 1.0)),
                    t.math("MULTIPLY", mud_o,
                           t.maprange(t.noise(t.vmath("SCALE", NZ, scale=6.0),
                                              260.0, 8.0, 0.78),
                                      0.30, 0.72, 0.0, 1.0)))
    mudm = t.math("ADD", mudm, splash, clamp=True)
    zinc = t.cmix(t.maprange(mudm, 0.05, 0.55, 0.0, 0.90), zinc, PAL["mud"])

    # THE EXPOSED FACE IS NOT THE CLEAN FACE.  Rubber comes from the track, so
    # `film` is keyed to 1 - expo and the OUTBOARD flange -- the one the doppler
    # hover and this item's own macro actually look at -- was coming back as
    # bare zinc.  What lands on it instead is rain-driven grime: a thin
    # grey-brown wash that runs vertically and collects behind every fixing.
    weathn = t.noise(t.comb(t.math("MULTIPLY", ang, 22.0),
                            t.math("MULTIPLY", hz, 0.85), 0.0), 11.0, 8.0, 0.70)
    weath = t.math("MULTIPLY",
                   t.math("MULTIPLY", t.maprange(expo, 0.15, 0.95, 0.28, 1.0),
                          t.maprange(age, 0.0, 1.0, 0.20, 1.0)),
                   t.maprange(weathn, 0.26, 0.80, 0.05, 1.0))
    weath = t.math("MULTIPLY", weath, t.maprange(hz, 4.4, 0.35, 0.55, 1.0))
    zinc = t.cmix(t.math("MULTIPLY", weath, 0.46), zinc,
                  t.cmix(0.40, PAL["grime"], PAL["dust"]))

    alg = t.math("MULTIPLY", t.math("MULTIPLY",
                                    t.maprange(hz, 0.30, 0.00, 0.0, 1.0),
                                    algae_o),
                 t.math("MULTIPLY", t.maprange(crev, 0.0, 1.0, 0.35, 1.0),
                        t.maprange(t.noise(t.vmath("SCALE", NZ, scale=2.2),
                                           48.0, 7.0, 0.7), 0.36, 0.72, 0.0, 1.0)))
    zinc = t.cmix(t.maprange(alg, 0.05, 0.60, 0.0, 0.72), zinc, PAL["algae"])

    # rain wash: vertical clean streaks cut back through the film on the faces
    # that are actually rained on
    wash = t.wave(t.comb(t.math("MULTIPLY", ang, 34.0),
                         t.math("MULTIPLY", hz, 0.22), 0.0), 1.0, 2.6, 5.0)
    washm = t.math("MULTIPLY", t.maprange(wash, 0.52, 0.92, 0.0, 1.0),
                   t.math("MULTIPLY", t.maprange(up, -0.2, 0.5, 0.15, 1.0),
                          t.maprange(hz, 0.10, 1.60, 0.2, 1.0)))
    zinc = t.cmix(t.math("MULTIPLY", washm, 0.34), zinc,
                  t.cmix(0.35, PAL["zinc_dull"], PAL["white_rust"]))

    # ------------------------------------------------- 5. A PAINT BAND
    bandm = t.math("MULTIPLY", paint,
                   t.math("MULTIPLY", t.maprange(hz, 1.44, 1.50, 0.0, 1.0),
                          t.maprange(hz, 1.66, 1.60, 0.0, 1.0)))
    chipn = t.noise(t.vmath("SCALE", NZ, scale=6.0), 190.0, 7.0, 0.72)
    bandm = t.math("MULTIPLY", bandm, t.maprange(chipn, 0.22, 0.52, 1.0, 0.35))
    base = t.cmix(bandm, zinc, band)

    # ------------------------------------------------------- 6. ROUGHNESS
    # Zinc is not a mirror and it is not chalk.  Fresh spangle is 0.30-0.42;
    # weathered carbonate is 0.78-0.90; rust is 0.92; a strimmed scar is 0.24
    # because bare steel that has just been abraded is BRIGHTER than anything
    # else on the post, and that contrast is most of what sells it.
    # Per-CRYSTAL roughness, not just per-surface: adjacent crystals of a real
    # spangle differ enough that one flashes and the one beside it does not.
    rough = t.fmix(t.maprange(cellv, 0.05, 0.95, 0.0, 1.0), 0.46, 0.23)
    rough = t.fmix(t.maprange(t.sep(spang, 1), 0.1, 0.9, 0.0, 0.55), rough,
                   t.math("ADD", rough, 0.16))
    rough = t.fmix(t.maprange(age, 0.0, 1.0, 0.0, 1.0), rough, 0.66)
    rough = t.fmix(t.math("MULTIPLY", weath, 0.85), rough, 0.80)
    rough = t.fmix(t.maprange(bl, 0.05, 0.65, 0.0, 1.0), rough, 0.88)
    rough = t.fmix(t.maprange(rustm, 0.02, 0.5, 0.0, 1.0), rough, 0.93)
    rough = t.fmix(t.math("MULTIPLY", dripv, 0.8), rough, 0.72)
    rough = t.fmix(t.maprange(dustm, 0.05, 0.7, 0.0, 0.9), rough, 0.86)
    rough = t.fmix(t.maprange(mudm, 0.05, 0.55, 0.0, 0.95), rough, 0.90)
    rough = t.fmix(t.math("MULTIPLY", film, 0.75), rough, 0.72)
    rough = t.fmix(t.math("MULTIPLY", strimb, 0.9), rough, 0.235)
    rough = t.fmix(t.math("MULTIPLY", bandm, 0.9), rough, 0.46)
    rough = t.math("ADD", rough,
                   t.maprange(t.noise(t.vmath("SCALE", NZ, scale=9.0),
                                      420.0, 5.0, 0.6), 0.3, 0.7, -0.035, 0.035))

    # ------------------------------------------------------------ 7. BUMP
    # Three scales, chained.  The spangle relief is real (the crystals stand
    # 10-25 microns proud); the carbonate is powdery and stands more; the rust
    # is the loudest thing on the surface.
    # b0 IS THE FACET and it comes first, because everything else is a film ON
    # TOP of a crystal that is already tilted.  0.55 x 0.012 x grad(25 h) is
    # about 2.8 deg of facet -- measured off a real spangle, where the crystals
    # are visibly not coplanar under a raking light.
    # STATED AS RADIANCE MODULATION, NOT AS MILLIMETRES (itemkit 5b, brief 4a).
    # What the eye judges is what a bump does to the LIGHT, and under this
    # film's 12.47 deg sun that carries a 4.52x amplifier: m = 2 sin(theta) /
    # tan(e).  Three amplitude sets were rendered and REJECTED on the human
    # figures and every one had been chosen in millimetres.
    #
    # NONE OF THESE SIX IS A RE-TUNE.  Each `modulation_pp` is the value that
    # reproduces the Distance this module already shipped, to 1e-16; what has
    # changed is that the stack now SAYS what it is aiming the light at.
    #
    # THE WAVELENGTH INCLUDES THE VECTOR SCALE, and that is why these numbers
    # are not `bump_relief_report`'s.  `t.noise(t.vmath("SCALE", NZ, scale=5.0),
    # 380.0, ...)` multiplies OBJECT metres by 5 before the texture sees them,
    # so its features are 5x smaller than 1/380 implies.  A reader of the Scale
    # socket alone gets 4.21 mm where the surface has 0.84 mm, and a factor of
    # five in the wavelength is a factor of five in m.
    #
    # Every band in every stage, with its weight in that stage's height sum,
    # its wavelength and what it does to the light at the SHIPPED depth:
    #
    #  [0] facet   w 0.103   lam  17.86 mm  m 1.072  geometry_fold
    #  [1] edge    w 0.55    lam  17.86 mm  m 0.308  isotropic_micro
    #      dend    w 0.45    lam   1.66 mm  m 2.602  hard_feature
    #  [2] bloom   w 0.75    lam  26.94 mm  m 0.261  isotropic_micro
    #      blotch  w 1.00    lam 235.29 mm  m 0.040  a mask shape, not relief
    #  [3] rust    w 1.00    lam  27.59 mm  m 0.902  isotropic_macro
    #      chip    w 1.00    lam   9.70 mm  m 2.479  hard_feature, gated `edgev`
    #      strim   w 1.00    lam   0.83 mm  m 8.659  gated to a 60-160 mm band
    #  [4] dust    w 1.00    lam   0.84 mm  m 1.513  hard_feature (0.31 px)
    #  [5] mud     w 0.90    lam   6.84 mm  m 2.137  hard_feature, gated `mud_o`
    #      splash  w 0.90    lam   1.03 mm  m 7.697  gated to a 150 mm strip
    #
    # THE NAMED BAND IS THE ONE THE `modulation_pp` REFERS TO: the ungated band
    # carrying most of the height, except in [2], where `bl` is a PRODUCT and
    # not a sum -- a 235 mm blotch has no gradient worth the name (m 0.040) and
    # all of that stage's read comes from the 27 mm mottle multiplied into it.
    # For a product the read belongs to the FINEST factor, not the largest.
    #
    # The four bands past m = 2 are all either GATED (chip by `edgev`, strim
    # and splash by hard height bands, mud by `mud_o`) or sub-pixel -- dend at
    # 1.66 mm is 0.62 px and dust at 0.84 mm is 0.31 px against the gate's
    # 373.3 px/m, so they lift roughness rather than build a crust.  NOTHING
    # here is an ungated, resolved, isotropic field above 1.5, which is the
    # felt this law exists to prevent.  strim at 8.66 is 4 % under the 9.04
    # ceiling the sun can deliver at all and is flagged in the report.
    #
    # [0] IS A FACET, so its height_pp is not 1.  `facet_h` is 25 * ((NZ -
    # cell centre) . (cell colour - 0.5)) -- a LINEAR ramp inside each crystal,
    # so it swings 25 * (cell pitch) * |r| p-p, with |r| = 0.5 rms for a
    # uniform cell colour and the pitch being 1/sc, NOT the 2.17x wavelength.
    # Calling it 1.0 would claim a full-range ramp across every crystal and
    # would state m = 4.98 for a surface that is measurably 6.8 deg of tilt.
    # m is INVARIANT to the sc that is chosen for it, because amplitude and
    # wavelength both go as 1/sc; 121.5 is the mid of the rolled-section branch
    # (78-165), which is most of the post's area.
    LAM_SPANGLE = K.VORONOI_WAVELENGTH_FACTOR / 121.5      # 17.86 mm
    LAM_BLOOM = K.NOISE_WAVELENGTH_FACTOR / (22.0 * 2.7)   # 26.94 mm
    LAM_RUST = K.NOISE_WAVELENGTH_FACTOR / 58.0            # 27.59 mm
    LAM_DUST = K.NOISE_WAVELENGTH_FACTOR / (380.0 * 5.0)   #  0.84 mm
    LAM_MUD = K.NOISE_WAVELENGTH_FACTOR / (78.0 * 3.0)     #  6.84 mm
    PITCH_SPANGLE = LAM_SPANGLE / K.VORONOI_WAVELENGTH_FACTOR   # 1/sc, 8.23 mm
    b0 = t.bump(facet_h, 0.55, modulation_pp=1.07250,
                wavelength_m=LAM_SPANGLE,
                height_pp=25.0 * 0.5 * PITCH_SPANGLE)
    b1 = t.bump(t.math("ADD", t.math("MULTIPLY", edgem, 0.55),
                       t.math("MULTIPLY", t.maprange(dend, 0.2, 0.8, 0.0, 1.0),
                              0.45)), 0.22, normal=b0,
                modulation_pp=0.307787, wavelength_m=LAM_SPANGLE,
                height_pp=0.55)
    b2 = t.bump(t.maprange(bl, 0.05, 0.70, 0.0, 1.0), 0.30, normal=b1,
                modulation_pp=0.26094, wavelength_m=LAM_BLOOM, height_pp=0.75)
    b3 = t.bump(t.maprange(rustm, 0.02, 0.60, 0.0, 1.0), 0.55, normal=b2,
                modulation_pp=0.90178, wavelength_m=LAM_RUST)
    b4 = t.bump(t.maprange(t.noise(t.vmath("SCALE", NZ, scale=5.0), 380.0,
                                   6.0, 0.7), 0.25, 0.75, 0.0, 1.0),
                0.13, normal=b3,
                modulation_pp=1.51341, wavelength_m=LAM_DUST)
    b5 = t.bump(t.math("MULTIPLY", mudm, 0.9), 0.42, normal=b4,
                modulation_pp=2.13660, wavelength_m=LAM_MUD, height_pp=0.90)

    # ------------------------------------------------------------ 8. OUTPUT
    bsdf = t.n("ShaderNodeBsdfPrincipled")
    t.pin(bsdf, 0, base)
    for nm, v in (("Roughness", rough), ("Normal", b5)):
        if nm in bsdf.inputs:
            t.pin(bsdf, bsdf.inputs.find(nm), v)
    if "Metallic" in bsdf.inputs:
        met = t.fmix(t.maprange(rustm, 0.02, 0.55, 0.0, 1.0),
                     t.fmix(t.maprange(bl, 0.08, 0.70, 0.0, 1.0), 0.92, 0.16),
                     0.05)
        met = t.fmix(t.math("MULTIPLY", bandm, 0.95), met, 0.0)
        met = t.fmix(t.math("MULTIPLY", mudm, 0.9), met, 0.0)
        t.pin(bsdf, bsdf.inputs.find("Metallic"), met)
    if "IOR" in bsdf.inputs:
        bsdf.inputs["IOR"].default_value = 2.6
    out = t.n("ShaderNodeOutputMaterial")
    t.t.links.new(bsdf.outputs[0], out.inputs["Surface"])
    del dentv, downm, is_weld, weldv, kind
    return t.m


def mat_fastener():
    """The bolts.  A different alloy and a different history from the post:
    they were hot-dip spun (thinner coat, no spangle to speak of), they were
    turned by a spanner so the flats are burnished, and their threads hold
    water in the root — so they rust from the thread out, not from the edge in.
    """
    name = PFX + "Fastener"
    if name in bpy.data.materials:
        return bpy.data.materials[name]
    t = NT(name)
    A = PFX.lower()
    co = t.n("ShaderNodeTexCoord")
    OBJ = (co, 3)
    ofs = t.comb(t.attr(A + "ofs_x", 2, "OBJECT"),
                 t.attr(A + "ofs_y", 2, "OBJECT"),
                 t.attr(A + "ofs_z", 2, "OBJECT"))
    NZ = t.vmath("ADD", OBJ, ofs)
    hz = t.attr(A + "hz")
    edgev = t.attr(A + "edge")
    barev = t.attr(A + "bare")
    crev = t.attr(A + "crev")
    age = t.attr(A + "age", 2, "OBJECT")
    rust_o = t.attr(A + "rust", 2, "OBJECT")
    mud_o = t.attr(A + "mud", 2, "OBJECT")
    dust_o = t.attr(A + "dust", 2, "OBJECT")
    up = t.sep(t.geo(1), 2)
    upm = t.maprange(up, 0.05, 0.80, 0.0, 1.0)

    micro = t.vor(NZ, 460.0, "F1", 1, 0.95)
    grain = t.noise(NZ, 1400.0, 4.0, 0.55)
    col = t.cmix(t.maprange(t.sep(micro, 0), 0.15, 0.9, 0.0, 1.0),
                 PAL["zinc_dull"], PAL["zinc_fresh"])
    col = t.cmix(t.maprange(grain, 0.3, 0.7, 0.0, 0.30), col, PAL["zinc_dark"])
    col = t.cmix(t.maprange(age, 0.1, 1.0, 0.0, 0.62), col, PAL["zinc_dull"])

    # burnish on the flats: a spanner polished them and nothing else
    burn = t.math("MULTIPLY", t.maprange(edgev, 0.4, 1.0, 0.0, 1.0),
                  t.maprange(t.noise(t.vmath("SCALE", NZ, scale=7.0), 300.0,
                                     5.0, 0.6), 0.35, 0.72, 0.0, 1.0))
    col = t.cmix(t.math("MULTIPLY", burn, 0.42), col, PAL["steel_bare"])

    rn = t.noise(t.vmath("SCALE", NZ, scale=2.2), 120.0, 9.0, 0.75)
    rustm = t.math("MULTIPLY",
                   t.math("ADD", barev, t.math("MULTIPLY", crev, 0.55),
                          clamp=True),
                   t.math("MULTIPLY", rust_o,
                          t.maprange(rn, 0.28, 0.78, 0.10, 1.0)))
    rustm = t.math("ADD", rustm,
                   t.math("MULTIPLY", t.maprange(age, 0.3, 1.0, 0.0, 0.55),
                          t.maprange(rn, 0.45, 0.85, 0.0, 1.0)), clamp=True)
    col = t.cmix(t.maprange(rustm, 0.03, 0.55, 0.0, 1.0), col,
                 t.cmix(t.maprange(rn, 0.3, 0.75, 0.0, 1.0),
                        PAL["rust_dark"], PAL["rust_bright"]))
    dustm = t.math("MULTIPLY", t.math("MULTIPLY", upm, dust_o),
                   t.maprange(t.noise(t.vmath("SCALE", NZ, scale=3.0), 90.0,
                                      6.0, 0.6), 0.3, 0.8, 0.2, 1.0))
    col = t.cmix(t.maprange(dustm, 0.05, 0.7, 0.0, 0.55), col, PAL["dust"])
    mudm = t.math("MULTIPLY", t.maprange(hz, 0.40, 0.02, 0.0, 1.0),
                  t.math("MULTIPLY", mud_o,
                         t.maprange(t.noise(t.vmath("SCALE", NZ, scale=4.0),
                                            150.0, 7.0, 0.7),
                                    0.35, 0.75, 0.0, 1.0)))
    col = t.cmix(t.maprange(mudm, 0.05, 0.55, 0.0, 0.85), col, PAL["mud"])

    rough = t.fmix(t.maprange(t.sep(micro, 0), 0.1, 0.9, 0.0, 1.0), 0.36, 0.28)
    rough = t.fmix(t.maprange(age, 0.0, 1.0, 0.0, 0.8), rough, 0.62)
    rough = t.fmix(t.maprange(rustm, 0.03, 0.5, 0.0, 1.0), rough, 0.92)
    rough = t.fmix(t.math("MULTIPLY", burn, 0.8), rough, 0.19)
    rough = t.fmix(t.maprange(mudm, 0.05, 0.55, 0.0, 0.9), rough, 0.90)
    # STATED AS RADIANCE MODULATION, NOT AS MILLIMETRES (itemkit 5b, brief 4a).
    # Not a re-tune: each `modulation_pp` reproduces the Distance this material
    # shipped.  Each of these three is a SINGLE band mapped full range, so
    # height_pp is 1.0 and there is nothing to choose between.
    #
    #  [0] cell    lam  4.72 mm  m 0.361  isotropic_micro   spun-dip mosaic
    #  [1] rust    lam  6.06 mm  m 2.054  hard_feature      gated `bare`/`crev`
    #  [2] grain   lam  1.14 mm  m 0.397  isotropic_micro   mill grain, 0.43 px
    #
    # [1]'s wavelength carries the 2.2 the vector is scaled by before `rn` sees
    # it -- 6.06 mm, not the 13.33 mm the Scale socket alone says.  It is a
    # rust scab, it only exists where `barev`/`crev` say the zinc has gone, and
    # a scab has a real lifted edge, so hard_feature is the band it belongs in.
    LAM_CELL = K.VORONOI_WAVELENGTH_FACTOR / 460.0        #  4.72 mm
    LAM_SCAB = K.NOISE_WAVELENGTH_FACTOR / (120.0 * 2.2)  #  6.06 mm
    LAM_GRAIN = K.NOISE_WAVELENGTH_FACTOR / 1400.0        #  1.14 mm
    b1 = t.bump(t.maprange(t.sep(micro, 0), 0.1, 0.9, 0.0, 1.0), 0.15,
                modulation_pp=0.361063, wavelength_m=LAM_CELL)
    b2 = t.bump(t.maprange(rustm, 0.03, 0.6, 0.0, 1.0), 0.50, normal=b1,
                modulation_pp=2.05434, wavelength_m=LAM_SCAB)
    b3 = t.bump(t.maprange(grain, 0.3, 0.7, 0.0, 1.0), 0.10, normal=b2,
                modulation_pp=0.397364, wavelength_m=LAM_GRAIN)
    bsdf = t.n("ShaderNodeBsdfPrincipled")
    t.pin(bsdf, 0, col)
    t.pin(bsdf, bsdf.inputs.find("Roughness"), rough)
    t.pin(bsdf, bsdf.inputs.find("Normal"), b3)
    met = t.fmix(t.maprange(rustm, 0.03, 0.55, 0.0, 1.0), 0.94, 0.08)
    met = t.fmix(t.maprange(mudm, 0.05, 0.6, 0.0, 0.9), met, 0.0)
    t.pin(bsdf, bsdf.inputs.find("Metallic"), met)
    out = t.n("ShaderNodeOutputMaterial")
    t.t.links.new(bsdf.outputs[0], out.inputs["Surface"])
    return t.m


def mat_conc():
    """Grout under a base plate.  Small, but it is 40 px of the frame on a
    plated post and a flat grey slab there is a placeholder."""
    name = PFX + "Grout"
    if name in bpy.data.materials:
        return bpy.data.materials[name]
    t = NT(name)
    A = PFX.lower()
    co = t.n("ShaderNodeTexCoord")
    ofs = t.comb(t.attr(A + "ofs_x", 2, "OBJECT"),
                 t.attr(A + "ofs_y", 2, "OBJECT"),
                 t.attr(A + "ofs_z", 2, "OBJECT"))
    NZ = t.vmath("ADD", (co, 3), ofs)
    agg = t.vor(NZ, 220.0, "F1", 1, 0.9)
    fines = t.noise(NZ, 900.0, 5.0, 0.6)
    stain = t.noise(t.vmath("SCALE", NZ, scale=1.4), 12.0, 8.0, 0.7)
    col = t.cmix(t.maprange(t.sep(agg, 0), 0.2, 0.9, 0.0, 1.0),
                 PAL["conc"], (0.220, 0.214, 0.200))
    col = t.cmix(t.maprange(fines, 0.3, 0.7, 0.0, 0.35), col, PAL["grime"])
    col = t.cmix(t.maprange(stain, 0.35, 0.75, 0.0, 0.55), col, PAL["dust"])
    rough = t.fmix(t.maprange(fines, 0.2, 0.8, 0.0, 1.0), 0.86, 0.96)
    # STATED AS RADIANCE MODULATION, NOT AS MILLIMETRES (itemkit 5b, brief 4a).
    # Not a re-tune: both reproduce the Distance this material shipped.  Both
    # are a single band mapped full range, so height_pp is 1.0.
    #
    #  [0] agg     lam  9.86 mm  m 1.779  hard_feature      aggregate mosaic
    #  [1] fines   lam  1.78 mm  m 1.266  above isotropic_macro, 0.66 px
    #
    # [0] IS NOT AN ISOTROPIC FIELD, which is why 1.78 is left standing where
    # an ungated crumple at that depth would be the felt this law exists to
    # prevent.  Voronoi F1's Colour output is piecewise CONSTANT -- one flat
    # value per cell -- so the whole of its gradient sits on the cell walls: it
    # is a mosaic of steps, and every step is an arris between two pieces of
    # exposed aggregate.  hard_feature is the band for an edge.
    # [1] at 1.266 is 33 % over isotropic_macro and IS ungated.  It is left
    # alone because it is under the 1.5 ceiling and because 1.78 mm is 0.66 px
    # at the gate's 373.3 px/m -- it lifts roughness, it cannot build a crust.
    LAM_AGG = K.VORONOI_WAVELENGTH_FACTOR / 220.0     #  9.86 mm
    LAM_FINES = K.NOISE_WAVELENGTH_FACTOR / 900.0     #  1.78 mm
    b1 = t.bump(t.maprange(t.sep(agg, 0), 0.2, 0.9, 0.0, 1.0), 0.35,
                modulation_pp=1.77915, wavelength_m=LAM_AGG)
    b2 = t.bump(t.maprange(fines, 0.2, 0.8, 0.0, 1.0), 0.20, normal=b1,
                modulation_pp=1.26589, wavelength_m=LAM_FINES)
    bsdf = t.n("ShaderNodeBsdfPrincipled")
    t.pin(bsdf, 0, col)
    t.pin(bsdf, bsdf.inputs.find("Roughness"), rough)
    t.pin(bsdf, bsdf.inputs.find("Normal"), b2)
    out = t.n("ShaderNodeOutputMaterial")
    t.t.links.new(bsdf.outputs[0], out.inputs["Surface"])
    return t.m


