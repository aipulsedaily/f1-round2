def fillet_weld(acc, path, leg, e_a, e_b, lod, mat=0, seed=0, nseg=None,
                convex=0.12, **attr):
    """A fillet weld along `path`, with legs on the two faces `e_a`, `e_b`.

    A weld is not a chamfer.  It is a slightly convex bead with a TOE on each
    leg, laid down in overlapping crescents that leave a ripple with a 3.2 mm
    pitch — 4.6 px here — and it starts and stops at a crater.  Modelling it as
    a 45 deg bevel is exactly the "smooth tube" failure one scale down.
    """
    P = np.asarray(path, float)
    m = len(P)
    L = LOD_SPEC[lod]
    k = nseg if nseg is not None else (9 if lod >= 3 else (6 if lod == 2 else 4))
    a = unit(e_a)
    b = unit(e_b)
    # bead cross-section in the (a, b) plane, from the toe on a to the toe on b
    t = np.linspace(0.0, 1.0, k)
    ang = t * (math.pi / 2.0)
    ra = leg * (1.0 + convex)
    prof_a = np.cos(ang) * ra
    prof_b = np.sin(ang) * ra
    # pull the middle out to make it convex, and flatten the toes
    bulge = np.sin(ang * 2.0) ** 1.2
    prof_a = prof_a * (1.0 + convex * 0.55 * bulge)
    prof_b = prof_b * (1.0 + convex * 0.55 * bulge)
    arc = np.concatenate([[0.0], np.cumsum(np.linalg.norm(np.diff(P, axis=0),
                                                          axis=1))])
    ripple = np.zeros(m)
    if L["weldrip"]:
        ph = arc / 0.0032
        ripple = (0.00030 * (np.abs((ph - np.floor(ph)) - 0.5) * 2.0 - 0.5)
                  + 0.00016 * (fbm1(arc * 220.0, seed=seed + 3, oct=2) - 0.5))
        # craters at the start and the stop
        ripple -= 0.0009 * np.exp(-((arc / 0.010) ** 2))
        ripple -= 0.0009 * np.exp(-(((arc[-1] - arc) / 0.012) ** 2))
    scale = 1.0 + ripple / max(leg, 1e-6)
    V = (P[:, None, :]
         + a[None, None, :] * (prof_a[None, :] * scale[:, None])[:, :, None]
         + b[None, None, :] * (prof_b[None, :] * scale[:, None])[:, :, None])
    q = ring_faces(m, k, closed=False)
    acc.add(V.reshape(-1, 3), quads=q, mat=mat, kind=K_WELD, weldv=1.0,
            arc=np.tile(arc[:, None], (1, k)).ravel(), **attr)


