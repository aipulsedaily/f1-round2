_AW = None
_AW_TRIED = False


def _armco():
    """build_barriers' barrier polyline, via armco_w_beam, or None."""
    global _AW, _AW_TRIED
    if not _AW_TRIED:
        _AW_TRIED = True
        try:
            import armco_w_beam as _m
            _AW = _m
        except Exception as e:                              # pragma: no cover
            _AW = None
            log("WARNING: armco_w_beam not importable (%s). The fence line will "
                "be rebuilt from world_contract with NO history jitter, which "
                "can put it up to %.2f m off the guardrail it is supposed to "
                "stand behind." % (e, C.BARRIER_JITTER_MAX_M))
    return _AW


_LINE_CACHE = {}


def barrier_line(side, ds=0.5):
    """The barrier polyline this fence follows, in the WORLD frame."""
    key = (side, ds)
    if key in _LINE_CACHE:
        return _LINE_CACHE[key]
    aw = _armco()
    if aw is not None:
        out = aw.barrier_line(side, ds)
    else:                                                   # pragma: no cover
        s = np.arange(0.0, C.LAP, ds)
        off = C.barrier_offset(s, side)
        P = np.asarray(C.su_to_world(s, off * side), float)
        P[:, 2] = C.ground_z(s, off, side)
        Pc = np.vstack([P, P[:1]])
        sc = np.concatenate([s, [C.LAP]])
        seg = np.linalg.norm(np.diff(Pc, axis=0)[:, :2], axis=1)
        L = np.concatenate([[0.0], np.cumsum(seg)])
        out = dict(P=Pc, s=sc, L=L, total=float(L[-1]), side=side)
    _LINE_CACHE[key] = out
    return out


def _frame_at(ln, u, side):
    """(centre, tangent, outboard-normal) on the barrier line at arc length u."""
    P, L = ln["P"], ln["L"]
    c = np.array([np.interp(u, L, P[:, k]) for k in range(3)])
    du = (np.array([np.interp(u + 1.0, L, P[:, k]) for k in range(3)]) -
          np.array([np.interp(u - 1.0, L, P[:, k]) for k in range(3)]))
    T = unit(du)
    R = unit(np.array([T[1], -T[0], 0.0]))
    return c, T, (-float(side)) * R          # +N is AWAY from the track


class Post(object):
    """One catch-fence post.  Everything a dependant or the mesher needs."""
    __slots__ = (
        "idx", "side", "pi", "s", "arc", "base", "axis", "T", "N", "ground_z",
        "sec", "stand_h", "embed", "length", "lean_deg", "roll_deg", "yaw_deg",
        "twist_deg", "bow_n", "bow_t", "batch", "galv_age", "bloom", "rust",
        "dust", "mud", "algae", "lot", "base_kind", "cleat_z", "n_cleat",
        "tag_no", "tag_z", "damaged", "kink_z", "kink_deg", "buckle",
        "splice_z", "raker", "raker_z", "raker_reach", "spare_holes",
        "cap_plate", "paint_band", "brand", "strimmer", "dip_down",
        "run_end", "seed", "lod", "ground_owner", "present", "road_u",
        "road_s")

    def __init__(self, **kw):
        for k in self.__slots__:
            setattr(self, k, kw.get(k))

    @property
    def name(self):
        return "%sPost_%s_%04d" % (PFX, "L" if self.side > 0 else "R", self.pi)

    def frame(self):
        """(R, O): the object's placement.  Columns of R are the local x, y, z
        axes in world.  Local +x = T (along the fence), +y = N (outboard),
        +z = up.  The lean lives in the MESH, not in the matrix, because a
        kinked post has no single axis and a dependant asking `axis` deserves
        the erection axis rather than an average of a bend."""
        z = np.array([0.0, 0.0, 1.0])
        x = unit(self.T - z * float(np.dot(self.T, z)))
        y = unit(np.cross(z, x))
        if float(np.dot(y, self.N)) < 0.0:
            y = -y
        R = np.stack([x, y, z], axis=1)
        return R, np.array(self.base, float)


_POSTS = {}


# A post standing this close to the racing surface is ON THE ROAD.  Half the
# deepest section is 102 mm; 0.60 m leaves a courtesy margin and still lets the
# fence line sit against the true edge where the corridor genuinely runs there.
ROAD_KEEPOUT_M = 0.60


def post_sites(side=None, present_only=True):
    """-> [Post].  690 slots in total, of which the ones that would stand ON
    THE RACING SURFACE are marked `present = False` and are NOT built.

    Reproduces build_barriers.build_fence's station rule exactly: spans on
    SPAN_M of ARC LENGTH along the barrier polyline, gated by
    world_contract.fence_allowed, offset SET_BACK_M outboard of the barrier
    face.  `present_only=False` returns the whole slate including the
    suppressed ones, which is what the defect report needs.

    WHY ANY OF THEM ARE SUPPRESSED.  Around the T4 hairpin the contract's
    `barrier_offset` reaches 66.8 m on the left.  The hairpin doubles back, so
    at s = 780 a barrier 66.8 m outboard lands on the racing surface of the
    s = 1190 leg — one slot projects to |u| = 0.01 m, i.e. the centreline.
    That is a defect in the corridor, not in this item, and this item is not
    the right place to fix it; but it IS the right place to refuse to plant a
    6 m steel post in the middle of the track.  See `road_intrusions()`.
    """
    if side is None:
        return (post_sites(+1, present_only)
                + post_sites(-1, present_only))
    side = int(side)
    if side in _POSTS:
        return ([p for p in _POSTS[side] if p.present] if present_only
                else _POSTS[side])
    ln = barrier_line(side)
    L, S, total = ln["L"], ln["s"], ln["total"]
    n = int(total // SPAN_M)
    seed = 7200 + (side > 0)
    out = []
    allowed = {}
    for pi in range(n + 1):
        u = pi * SPAN_M
        sj = float(np.interp(u, L, S))
        allowed[pi] = bool(C.fence_allowed(np.array([sj]), side)[0])
    nan_z = 0
    for pi in range(n + 1):
        if not allowed[pi]:
            continue
        u = pi * SPAN_M
        sj = float(np.interp(u, L, S))
        c, T, N = _frame_at(ln, u, side)
        base_xy = c[:2] + N[:2] * SET_BACK_M
        gz, own = C.world_ground_z(np.array([base_xy[0]]),
                                   np.array([base_xy[1]]))
        gz = float(gz[0])
        owner = str(own[0])
        if not np.isfinite(gz):
            # LAW 5 says never an assumed z.  The honest fallback is the
            # barrier line's own datum at this station, and it is COUNTED.
            gz = float(c[2])
            owner = "FALLBACK_BARRIER_LINE"
            nan_z += 1
        p = _spec_post(pi, side, sj, u, np.array([base_xy[0], base_xy[1], gz]),
                       T, N, gz, owner, seed, allowed)
        p.idx = len(out)
        out.append(p)
    if nan_z:
        log("NOTE side %+d: %d post bases fell outside world_ground_z's "
            "coverage and took the barrier-line datum instead." % (side, nan_z))
    # --- ON THE ROAD?  measured, not assumed --------------------------------
    X = np.array([p.base[0] for p in out])
    Y = np.array([p.base[1] for p in out])
    sp, up = C.world_su(X, Y)
    ve = C.verge_edge(sp)
    sup = 0
    for p, s_, u_, e_ in zip(out, sp, up, ve):
        p.road_s = float(s_)
        p.road_u = float(abs(u_)) - float(e_)
        p.present = p.road_u > ROAD_KEEPOUT_M
        sup += (not p.present)
    if sup:
        log("REFUSING to plant %d of %d posts on side %+d: their base falls "
            "within %.2f m of the racing surface edge. This is a corridor "
            "defect upstream (barrier_offset reaches 66.8 m where the hairpin "
            "doubles back); see road_intrusions()." % (sup, len(out), side,
                                                       ROAD_KEEPOUT_M))
    _POSTS[side] = out
    return [p for p in out if p.present] if present_only else out


def road_intrusions():
    """-> the slots this module refused to build, worst-first, in the shape
    tools/placement_gate.py reports findings: how deep into the road corridor
    the post would have stood, in metres."""
    out = []
    for sd in (+1, -1):
        for p in post_sites(sd, present_only=False):
            if p.present:
                continue
            out.append(dict(side=p.side, pi=p.pi, s=float(p.s),
                            projected_s=float(p.road_s),
                            world=tuple(float(v) for v in p.base),
                            intrusion_m=float(ROAD_KEEPOUT_M - p.road_u),
                            barrier_offset_m=float(
                                C.barrier_offset(np.array([p.s]), p.side)[0])))
    out.sort(key=lambda d: -d["intrusion_m"])
    return out


def _spec_post(pi, side, s, u, base, T, N, gz, owner, seed, allowed):
    """Everything about ONE post that is not its mesh.

    The variation axes the manifest names are lean, galvanising age and the
    base collar.  None of them is a random rotation:

      LEAN is three separate physical causes with different signatures.  A
      BATCH bias (one gang, one string line, one afternoon: 6-30 consecutive
      posts share it), a per-post plumb error that is NORMAL not uniform, and a
      standing outward pull of 0.32 deg because a tensioned 3.6 m fabric drags
      every post toward the track over twenty years.  Driven posts get 2.1x the
      plumb error of concreted ones, because that is what a post driver does.

      GALVANISING AGE is a property of the DIP, so it is a batch property too,
      modulated per post by how much sun and rain that post's aspect gets.  A
      post-by-post random age gives a fence that looks like static; a batched
      one gives a fence with a history of repairs, which is what a circuit is.

      THE BASE is the collar item's, but which KIND of base decides the post's
      own geometry: a plated post carries a 300 mm plate, a fillet weld and
      four holding-down bolts, and a driven one does not.
    """
    batch = pi // rint(6, 30, seed, pi // 24, 3)
    bseed = seed * 977 + batch * 31 + (side > 0) * 7
    ps = seed * 31 + pi * 7 + (side > 0)

    sec = SECTIONS[int(np.searchsorted(_SEC_CDF, h01(bseed, 41)))]

    r = h01(ps, 5)
    base_kind = "concrete" if r < 0.62 else ("plate" if r < 0.86 else "driven")

    embed = EMBED_M * rnd(0.94, 1.12, ps, 9)
    if base_kind == "plate":
        embed = 0.0                    # the steel stops at the plate
    length = POST_L * rnd(0.996, 1.004, ps, 11)
    stand_h = (length - embed) if base_kind != "plate" else \
        (STAND_H * rnd(0.985, 1.015, ps, 13))

    drv = 2.1 if base_kind == "driven" else 1.0
    lean = (gauss(0.52 * drv, ps, 17) + 0.32
            + 1.15 * (h01(bseed, 19) - 0.5))
    lean = float(np.clip(lean, -2.6, 3.4))
    roll = float(np.clip(gauss(0.34 * drv, ps, 23), -1.5, 1.5))
    yaw = float(np.clip(gauss(0.55, ps, 29) + 1.4 * (h01(bseed, 31) - 0.5),
                        -2.4, 2.4))

    # mill camber is L/1000 by standard; wind set and mesh tension add to it
    bow_n = (0.0060 * rnd(-1.0, 1.0, ps, 37) + 0.0125 * h01(ps, 41))
    bow_t = 0.0050 * rnd(-1.0, 1.0, ps, 43)
    twist = float(np.clip(gauss(0.42, ps, 47), -1.3, 1.3))

    galv_age = clamp01(0.10 + 0.78 * h01(bseed, 53)
                       + 0.16 * (h01(ps, 59) - 0.5))
    bloom = clamp01(0.20 + 0.70 * h01(bseed, 61) * (0.35 + 0.9 * galv_age)
                    + 0.22 * (h01(ps, 67) - 0.5))
    rust = clamp01((galv_age ** 1.7) * (0.30 + 0.80 * h01(ps, 71)))
    dust = clamp01(0.22 + 0.62 * h01(ps, 73))
    mud = clamp01(0.15 + 0.75 * h01(ps, 79) ** 1.6)
    algae = clamp01((0.55 - 0.5 * float(np.dot(N, C.SUN_DIR)))
                    * (0.30 + 0.9 * h01(ps, 83)))
    lot = h01(bseed, 89) * 2.0

    # --- how many clamp cleats, and where -----------------------------------
    # The fabric is 3.6 m and is gripped at 4, 5 or 6 tiers depending on which
    # decade the run was built in.  The tier heights are NOT evenly spaced: the
    # bottom two are close together because that is where a wheel arrives.
    n_cleat = 4 + rint(0, 2, bseed, 97)
    t0 = MESH_BOT_NOM + rnd(-0.035, 0.055, ps, 101)
    span = MESH_H - 0.16
    frac = {4: (0.03, 0.30, 0.63, 0.965),
            5: (0.03, 0.22, 0.46, 0.71, 0.965),
            6: (0.02, 0.17, 0.35, 0.54, 0.76, 0.97)}[n_cleat]
    cleat_z = [t0 + span * f + rnd(-0.014, 0.014, ps, 103 + i)
               for i, f in enumerate(frac)]

    tag_no = 1000 + (0 if side > 0 else 2000) + pi * 2 + rint(0, 1, ps, 107)
    tag_z = rnd(1.42, 1.92, ps, 109)

    # --- has this post been hit? --------------------------------------------
    # A shakedown circuit has been used.  4.5 % of posts carry a permanent set
    # from an impact and 1.6 % have been spliced back together.  The height
    # band is the CAR's: a 2.005 m wide car with a 0.34 m ride height puts its
    # sidepod and front wing endplate between 0.30 and 0.95 m.
    damaged = chance(0.045, ps, 113)
    kink_z = rnd(0.62, 1.55, ps, 127) if damaged else 0.0
    kink_deg = (rnd(2.6, 13.0, ps, 131) * (1 if chance(0.72, ps, 137) else -1)) \
        if damaged else 0.0
    buckle = rnd(0.0016, 0.0060, ps, 139) if damaged else 0.0
    splice_z = rnd(2.05, 3.15, ps, 149) if chance(0.016, ps, 151) else 0.0

    # --- a stay, on the posts that need one ---------------------------------
    # Real practice: every run end, every change of direction, and roughly
    # every seventh post in a long straight run.
    end = (not allowed.get(pi - 1, False)) or (not allowed.get(pi + 1, False))
    raker = end or chance(0.155, ps, 157)
    raker_z = rnd(2.35, 3.05, ps, 163)
    raker_reach = rnd(1.75, 2.35, ps, 167)

    # --- holes that are not used any more -----------------------------------
    nsp = 0
    if chance(0.38, ps, 173):
        nsp = rint(1, 4, ps, 179)
    spare = []
    for k in range(nsp):
        spare.append(dict(z=rnd(0.35, 3.60, ps, 181 + k * 3),
                          u=rnd(-0.045, 0.045, ps, 182 + k * 3),
                          d=pick((0.0140, 0.0140, 0.0180, 0.0220),
                                 ps, 183 + k * 3),
                          face=-1.0 if chance(0.78, ps, 191 + k) else +1.0))

    return Post(
        pi=pi, side=side, s=s, arc=u, base=base, axis=None, T=T, N=N,
        ground_z=gz, ground_owner=owner, sec=sec, stand_h=stand_h,
        embed=embed, length=length, lean_deg=lean, roll_deg=roll, yaw_deg=yaw,
        twist_deg=twist, bow_n=bow_n, bow_t=bow_t, batch=batch,
        galv_age=galv_age, bloom=bloom, rust=rust, dust=dust, mud=mud,
        algae=algae, lot=lot, base_kind=base_kind, cleat_z=cleat_z,
        n_cleat=n_cleat, tag_no=tag_no, tag_z=tag_z, damaged=damaged,
        kink_z=kink_z, kink_deg=kink_deg, buckle=buckle, splice_z=splice_z,
        raker=raker, raker_z=raker_z, raker_reach=raker_reach,
        spare_holes=spare, cap_plate=chance(0.34, ps, 197),
        paint_band=chance(0.11, ps, 199), brand=rint(0, 29, ps, 211),
        strimmer=clamp01(h01(ps, 223) * 1.4), dip_down=chance(0.5, bseed, 227),
        run_end=end, seed=ps, lod=1)


# ==============================================================================
#  4.  THE POST'S OWN CURVE
# ==============================================================================
#
# A post is not a line segment.  It is a 6 m rolled member with a mill camber,
# a plumb error, a wind set, a twist, and — on the ones that have been hit — a
# plastic kink.  All of that lives in the CENTRELINE, which is why a post
# reads as a physical object from 2.6 m instead of as an extrusion.

def post_curve(p, z):
    """Centreline points and section frames at heights `z` above the ground
    line, in the post's LOCAL frame (x along the fence, y outboard, z up)."""
    z = np.asarray(z, float)
    lean = math.radians(p.lean_deg)
    roll = math.radians(p.roll_deg)
    # the erection axis: a tilt outboard (lean) and along the line (roll)
    ax = np.array([math.sin(roll), math.sin(lean),
                   math.sqrt(max(1e-9, 1.0 - math.sin(roll) ** 2
                                 - math.sin(lean) ** 2))])
    P = z[:, None] * ax[None, :]
    # mill camber + wind set: a half sine over the free length
    t = clamp01(z / max(p.stand_h, 0.1))
    bow = np.sin(np.pi * np.clip(t, 0.0, 1.0)) * (t > 0.0)
    P[:, 1] += p.bow_n * bow
    P[:, 0] += p.bow_t * bow
    if p.damaged and p.kink_z > 0.0:
        # a plastic hinge: everything above the kink rotates about it, and the
        # hinge itself is rounded over ~90 mm because steel does not fold.
        d = np.clip((z - p.kink_z) / 0.090, 0.0, None)
        s = np.where(d < 1.0, 0.5 * d * d, d - 0.5) * 0.090
        P[:, 1] += math.tan(math.radians(p.kink_deg)) * s
    return P, ax


def post_frames(p, z):
    """(C, eu, ev) — centreline and the two section axes at each height."""
    z = np.atleast_1d(np.asarray(z, float))
    Cc, ax = post_curve(p, z)
    # Analytic forward difference rather than np.gradient: a dependant asking
    # for the frame at ONE height is the commonest call and gradient needs
    # three samples, which is how `cleat_sites()` used to die.
    C2, _ = post_curve(p, z + 2.0e-4)
    dz = C2 - Cc
    Tv = dz / np.maximum(np.linalg.norm(dz, axis=1)[:, None], 1e-12)
    yaw = math.radians(p.yaw_deg)
    u0 = np.array([math.cos(yaw), math.sin(yaw), 0.0])
    eu = u0[None, :] - Tv * (Tv @ u0)[:, None]
    eu /= np.maximum(np.linalg.norm(eu, axis=1)[:, None], 1e-12)
    ev = np.cross(Tv, eu)
    # twist: the section rotates about its own axis up the post
    if abs(p.twist_deg) > 1e-6:
        a = np.radians(p.twist_deg) * clamp01(z / max(p.stand_h, 0.1))
        ca, sa = np.cos(a)[:, None], np.sin(a)[:, None]
        eu, ev = eu * ca + ev * sa, ev * ca - eu * sa
    return Cc, eu, ev


def local_point(p, z, u, v):
    """A point on/near the section at height z, offsets (u, v) in the section
    plane.  The one function every fixing, hole and dependant goes through."""
    zz = np.atleast_1d(np.asarray(z, float))
    Cc, eu, ev = post_frames(p, zz)
    uu = np.atleast_1d(np.asarray(u, float)) * np.ones(len(zz))
    vv = np.atleast_1d(np.asarray(v, float)) * np.ones(len(zz))
    return Cc + eu * uu[:, None] + ev * vv[:, None]


# ==============================================================================
#  5.  ACCUMULATOR AND PRIMITIVES
# ==============================================================================
#
# One Acc per POST, so a post is one object and the gate's per-instance
# statistics are genuinely per instance.
#
# ATTRIBUTES.  Eleven floats per vertex.  They exist because a material that
# has to work out what it is looking at from world coordinates cannot: at
# |P| ~ 1000 m the precision is gone, and "height above the ground line" is not
# a world z once the post leans.  So the geometry TELLS the shader what it is.

ATTR_F = ("kind", "arc", "ang", "hz", "expo", "crev", "edge", "weldv",
          "bare", "drip", "dent")

(K_STEEL, K_BOLT, K_WELD, K_CLEAT, K_TAG, K_PLATE, K_TUBE, K_CUT,
 K_MARK, K_ZINC, K_NUT) = range(11)


class Acc(object):
    def __init__(self, name):
        self.name = name
        self._V = []
        self._L = []          # flat loop index arrays
        self._T = []          # loop totals
        self._M = []          # per-face material index
        self._A = {a: [] for a in ATTR_F}
        self.n = 0
        self.nf = 0
        self.parts = 0

    # -- faces --------------------------------------------------------------
    def add(self, V, quads=None, tris=None, ngons=None, mat=0, **attr):
        V = np.ascontiguousarray(np.asarray(V, np.float64).reshape(-1, 3))
        m = V.shape[0]
        if m == 0:
            return 0
        base = self.n
        self._V.append(V)
        loops, tots = [], []
        if quads is not None and len(quads):
            q = np.asarray(quads, np.int64).reshape(-1, 4) + base
            loops.append(q.ravel())
            tots.append(np.full(q.shape[0], 4, np.int32))
        if tris is not None and len(tris):
            t = np.asarray(tris, np.int64).reshape(-1, 3) + base
            loops.append(t.ravel())
            tots.append(np.full(t.shape[0], 3, np.int32))
        if ngons:
            for g in ngons:
                g = np.asarray(g, np.int64).ravel() + base
                loops.append(g)
                tots.append(np.array([len(g)], np.int32))
        if loops:
            self._L.append(np.concatenate(loops))
            tt = np.concatenate(tots)
            self._T.append(tt)
            self._M.append(np.full(len(tt), mat, np.int32))
            self.nf += len(tt)
        for a in ATTR_F:
            v = attr.get(a, 0.0)
            if np.ndim(v) == 0:
                self._A[a].append(np.full(m, float(v), np.float32))
            else:
                self._A[a].append(np.broadcast_to(
                    np.asarray(v, np.float32).ravel(), (m,)).astype(np.float32))
        self.n += m
        self.parts += 1
        return base

    def solid(self, V, quads=None, tris=None, ngons=None, **kw):
        """Add a CLOSED solid, orienting every face outward by signed volume.
        Winding is the most tedious bug class in generated geometry and a
        flipped face under a 12.5 deg sun is a black hole in the frame."""
        V = np.asarray(V, np.float64).reshape(-1, 3)
        Q = None if quads is None else np.asarray(quads, np.int64).reshape(-1, 4)
        T = None if tris is None else np.asarray(tris, np.int64).reshape(-1, 3)
        vol = 0.0
        if T is not None and len(T):
            a, b, c = V[T[:, 0]], V[T[:, 1]], V[T[:, 2]]
            vol += float(np.einsum("ij,ij->i", a, np.cross(b, c)).sum())
        if Q is not None and len(Q):
            for (i, j, k) in ((0, 1, 2), (0, 2, 3)):
                a, b, c = V[Q[:, i]], V[Q[:, j]], V[Q[:, k]]
                vol += float(np.einsum("ij,ij->i", a, np.cross(b, c)).sum())
        if vol < 0.0:
            if Q is not None and len(Q):
                Q = Q[:, ::-1].copy()
            if T is not None and len(T):
                T = T[:, ::-1].copy()
            if ngons:
                ngons = [list(g)[::-1] for g in ngons]
        return self.add(V, quads=Q, tris=T, ngons=ngons, **kw)

    # -- output --------------------------------------------------------------
    def to_mesh(self, name=None):
        V = np.concatenate(self._V) if self._V else np.zeros((0, 3))
        L = np.concatenate(self._L) if self._L else np.zeros(0, np.int64)
        T = np.concatenate(self._T) if self._T else np.zeros(0, np.int32)
        M = np.concatenate(self._M) if self._M else np.zeros(0, np.int32)
        me = bpy.data.meshes.new(name or self.name)
        me.vertices.add(V.shape[0])
        me.vertices.foreach_set("co", V.astype(np.float32).ravel())
        me.loops.add(int(L.shape[0]))
        me.loops.foreach_set("vertex_index", L.astype(np.int32))
        me.polygons.add(int(T.shape[0]))
        ls = np.concatenate([[0], np.cumsum(T)[:-1]]).astype(np.int32) \
            if len(T) else np.zeros(0, np.int32)
        me.polygons.foreach_set("loop_start", ls)
        me.polygons.foreach_set("loop_total", T.astype(np.int32))
        me.polygons.foreach_set("material_index", M.astype(np.int32))
        me.update(calc_edges=True)
        for a in ATTR_F:
            at = me.attributes.new(PFX.lower() + a, "FLOAT", "POINT")
            at.data.foreach_set("value", np.concatenate(self._A[a])
                                if self._A[a] else np.zeros(0, np.float32))
        me.validate(verbose=False)
        return me

    def stats(self):
        T = np.concatenate(self._T) if self._T else np.zeros(0, np.int32)
        return dict(verts=self.n, faces=int(len(T)),
                    triangles=int(np.maximum(T - 2, 1).sum()), parts=self.parts)


def ring_faces(m, k, closed=True):
    i = np.arange(m - 1)[:, None]
    j = np.arange(k if closed else k - 1)[None, :]
    j1 = (j + 1) % k
    return np.stack([(i * k + j).ravel(), (i * k + j1).ravel(),
                     ((i + 1) * k + j1).ravel(), ((i + 1) * k + j).ravel()], 1)


def grid_quads(n, m):
    i = np.arange(n - 1)[:, None]
    j = np.arange(m - 1)[None, :]
    return np.stack([(i * m + j).ravel(), (i * m + j + 1).ravel(),
                     ((i + 1) * m + j + 1).ravel(),
                     ((i + 1) * m + j).ravel()], 1)


def fan(centre_idx, ring, reverse=False):
    b = np.asarray(ring, np.int64)
    a = np.full(len(b), centre_idx, np.int64)
    c = np.roll(b, -1)
    return np.stack([a, c, b], 1) if reverse else np.stack([a, b, c], 1)


def stations(a, b, base, refine=(), min_gap=None):
    """Station heights from a to b at `base` pitch, locally refined.

    `refine` is a list of (centre, half_width, step).  A post does not need
    55 mm stations for its whole 6 m — it needs them where the bolts, the
    ground line, the kink and the ends are, and 400 mm in the 1.2 m that is
    buried.  Grading here is worth more than a global density anywhere else.
    """
    pts = [np.arange(a, b + 1e-9, base), np.array([a, b], float)]
    for (c, h, st) in refine:
        lo, hi = max(a, c - h), min(b, c + h)
        if hi > lo + 1e-9:
            pts.append(np.arange(lo, hi + 1e-9, st))
    z = np.unique(np.concatenate(pts))
    z = z[(z >= a - 1e-9) & (z <= b + 1e-9)]
    gap = min_gap if min_gap is not None else base * 0.12
    keep = [z[0]]
    for x in z[1:-1]:
        if x - keep[-1] >= gap:
            keep.append(x)
    keep.append(z[-1])
    return np.array(keep)


def circle(n, r=1.0, phase=0.0):
    a = np.arange(n) * (2.0 * math.pi / n) + phase
    return np.stack([np.cos(a) * r, np.sin(a) * r], axis=1), a


def hexagon(af, n_flat=3, chamfer=0.0):
    """A hex head/nut outline across flats `af`, with the standard 30 deg
    chamfer expressed as a SMALLER outline used for the chamfered ring.  The
    corners are the circumscribed circle, af / cos(30)."""
    R = af / math.sqrt(3.0)                    # across corners / 2
    pts = []
    for k in range(6):
        a0 = k * math.pi / 3.0
        a1 = (k + 1) * math.pi / 3.0
        p0 = np.array([R * math.cos(a0), R * math.sin(a0)])
        p1 = np.array([R * math.cos(a1), R * math.sin(a1)])
        for i in range(n_flat):
            t = i / float(n_flat)
            pts.append(p0 * (1 - t) + p1 * t)
    P = np.array(pts)
    if chamfer > 0.0:
        # the chamfer cuts the corners back to a circle of radius af/2
        rad = np.linalg.norm(P, axis=1)
        k = np.minimum(1.0, (af * 0.5 + chamfer) / np.maximum(rad, 1e-9))
        P = P * k[:, None]
    return P


def frames_along(path, up_hint=(0.0, 0.0, 1.0)):
    """Parallel-transport frames.  (T, N, B), right-handed."""
    P = np.asarray(path, float)
    n = P.shape[0]
    T = np.zeros((n, 3))
    if n > 1:
        T[:-1] = P[1:] - P[:-1]
        T[-1] = T[-2]
    else:
        T[0] = (0.0, 0.0, 1.0)
    T /= np.maximum(np.linalg.norm(T, axis=1)[:, None], 1e-12)
    up = np.asarray(up_hint, float)
    N = np.zeros((n, 3))
    ref = up - T[0] * float(np.dot(T[0], up))
    if np.linalg.norm(ref) < 1e-6:
        ref = np.array([1.0, 0.0, 0.0]) - T[0] * T[0][0]
    N[0] = unit(ref)
    for i in range(1, n):
        v = N[i - 1] - T[i] * float(np.dot(T[i], N[i - 1]))
        if np.linalg.norm(v) < 1e-9:
            v = np.cross(T[i], N[i - 1])
        N[i] = unit(v)
    B = np.cross(T, N)
    return T, N, B


def sweep_ring(acc, path, prof2d, nrm2d=None, mat=0, caps=(True, True),
               close_prof=True, radial=None, **attr):
    """Sweep a 2-D outline along a 3-D path with parallel-transported frames.

    `prof2d` may be (K,2) — one outline for the whole sweep — or (M,K,2), one
    per station, which is what lets a tube end be pressed FLAT over its last
    90 mm without any modifier.  `radial` (M,K) displaces each point along its
    own outward normal, which is how a zinc run becomes geometry.
    """
    P = np.asarray(path, float)
    m = len(P)
    T, N, B = frames_along(P)
    pr = np.asarray(prof2d, float)
    if pr.ndim == 2:
        pr = np.tile(pr[None, :, :], (m, 1, 1))
    k = pr.shape[1]
    if radial is not None and nrm2d is not None:
        nn = np.asarray(nrm2d, float)
        if nn.ndim == 2:
            nn = np.tile(nn[None, :, :], (m, 1, 1))
        pr = pr + nn * np.asarray(radial, float)[:, :, None]
    V = (P[:, None, :]
         + N[:, None, :] * pr[:, :, 0][:, :, None]
         + B[:, None, :] * pr[:, :, 1][:, :, None])
    base = acc.n
    q = ring_faces(m, k, closed=close_prof)
    ng = []
    Vf = V.reshape(-1, 3)
    extra = []
    if caps[0]:
        ng.append(list(range(k - 1, -1, -1)))
    if caps[1]:
        ng.append(list(range((m - 1) * k, m * k)))
    acc.add(Vf, quads=q, ngons=ng, mat=mat, **attr)
    return base, V


def solid_of_revolution(acc, prof, nseg, mat=0, phase=0.0, close_top=False,
                        **attr):
    """`prof` is (K,2) of (radius, z), revolved.  Used for washers, bolt
    shanks, weld ends and the mushroomed head of a driven post."""
    a = np.arange(nseg) * (2.0 * math.pi / nseg) + phase
    ca, sa = np.cos(a), np.sin(a)
    P = np.asarray(prof, float)
    V = np.stack([P[:, 0][:, None] * ca[None, :],
                  P[:, 0][:, None] * sa[None, :],
                  np.tile(P[:, 1][:, None], (1, nseg))], axis=2)
    q = ring_faces(len(P), nseg, closed=True)
    return acc.add(V.reshape(-1, 3), quads=q, mat=mat, **attr)


def box_solid(acc, ctr, ex, ey, ez, mat=0, chamf=0.0, **attr):
    """An axis-triple box.  `chamf` shrinks the top face, which is what turns
    a slab into a rolled plate with a rounded top arris."""
    V, Q = [], []
    for sz in (-1.0, 1.0):
        for sy in (-1.0, 1.0):
            for sx in (-1.0, 1.0):
                V.append(np.asarray(ctr, float) + ex * sx + ey * sy + ez * sz)
    V = np.array(V)
    Q = np.array([(0, 1, 3, 2), (4, 5, 7, 6), (0, 1, 5, 4),
                  (2, 3, 7, 6), (0, 2, 6, 4), (1, 3, 7, 5)])
    return acc.solid(V, quads=Q, mat=mat, **attr)


def plate_solid(acc, ctr, ex, ey, ez, rc=0.0025, nseg=4, mat=0, **attr):
    """A flat plate with radiused corners AND a rolled arris on both faces.
    A 10 mm plate seen at 2.6 m is 14 px thick; a square-cut edge on it reads
    as cardboard, a 1 mm break on the arris reads as steel."""
    lu = float(np.linalg.norm(ex))
    lv = float(np.linalg.norm(ey))
    tt = float(np.linalg.norm(ez))
    eu, ev, ew = ex / lu, ey / lv, ez / tt
    br = min(0.0010, tt * 0.22)
    prof = _rounded_box(lu, lv, max(rc, br * 1.2), max(lu, lv) / 3.0,
                        rc / max(nseg, 1), T_TOE)[0]
    layers = [(-tt, br), (-tt + br, 0.0), (tt - br, 0.0), (tt, br)]
    Vs = []
    for (zz, inset) in layers:
        pp = prof * (1.0 - 0.0)                 # inset applied radially below
        if inset > 0.0:
            nrmz = prof / np.maximum(np.linalg.norm(prof, axis=1)[:, None], 1e-9)
            pp = prof - nrmz * inset
        Vs.append(np.asarray(ctr, float)[None, :]
                  + eu[None, :] * pp[:, 0][:, None]
                  + ev[None, :] * pp[:, 1][:, None]
                  + ew[None, :] * zz)
    V = np.concatenate(Vs)
    k = len(prof)
    q = ring_faces(4, k, closed=True)
    ng = [list(range(k - 1, -1, -1)), list(range(3 * k, 4 * k))]
    return acc.solid(V, quads=q, ngons=ng, mat=mat, **attr)


# ==============================================================================
#  6.  FASTENERS  —  the thing you actually look at from 2.6 m
# ==============================================================================
#
# An M12 hex head is 27 px across at the filmed distance and there are ten of
# them on a post.  They are the smallest object in the frame that a viewer
# knows the size of, which makes them the scale reference for everything else.
# So: a real 30 deg head chamfer (1.7 px, and it is the only lit line on the
# head), a real washer face under it, a real rolled thread at 1.75 mm pitch
# (2.5 px per turn), and a real nut with chamfers on BOTH faces and a visible
# threaded bore at the end.
#
# `frame` is (origin, axis, ref) with `axis` pointing OUT of the joint, i.e.
# the direction the head faces.

def _fr(o, axis, ref=None):
    a = unit(axis)
    r = np.array([0.0, 0.0, 1.0]) if ref is None else unit(np.asarray(ref, float))
    if abs(float(np.dot(a, r))) > 0.98:
        r = np.array([1.0, 0.0, 0.0])
    e1 = unit(r - a * float(np.dot(a, r)))
    e2 = np.cross(a, e1)
    return np.asarray(o, float), a, e1, e2


def _emit_rev(acc, o, a, e1, e2, rings, nseg, mat, phase=0.0, cap=None, **attr):
    """`rings` is a list of (radius, along-axis offset), revolved.

    `cap` = (bool, bool) forces the end n-gons; None auto-caps any end whose
    radius is non-zero.  A WASHER MUST PASS cap=(False, False) and close its
    own profile through the bore, because the auto rule would lay a disc across
    the bore at both faces — and those discs land exactly on the clamp bar and
    on the head's washer face, i.e. two z-fighting planes on the one fastener
    the eye uses to judge the scale of everything else in the frame.
    """
    ang = np.arange(nseg) * (2.0 * math.pi / nseg) + phase
    ca, sa = np.cos(ang), np.sin(ang)
    R = np.asarray([r for (r, _) in rings], float)
    Z = np.asarray([z for (_, z) in rings], float)
    V = (o[None, None, :] + a[None, None, :] * Z[:, None, None]
         + e1[None, None, :] * (R[:, None] * ca[None, :])[:, :, None]
         + e2[None, None, :] * (R[:, None] * sa[None, :])[:, :, None])
    k = nseg
    q = ring_faces(len(R), k, closed=True)
    ng = []
    c0 = (R[0] > 1e-6) if cap is None else bool(cap[0])
    c1 = (R[-1] > 1e-6) if cap is None else bool(cap[1])
    if c0:
        ng.append(list(range(k - 1, -1, -1)))
    if c1:
        ng.append(list(range((len(R) - 1) * k, len(R) * k)))
    return acc.solid(V.reshape(-1, 3), quads=q, ngons=ng, mat=mat, **attr)


def washer_rings(hole, od, t):
    """A closed annulus profile: bottom face, outer break, outer face, top
    break, top face, bore wall, back to the start."""
    rh = hole * 0.5 * 1.03
    rw = od * 0.5
    br = min(0.0010, t * 0.30)
    return [(rh, 0.0), (rw - br, 0.0), (rw, br), (rw, t - br),
            (rw - br, t), (rh, t), (rh, 0.0)]


def _emit_prism(acc, o, a, e1, e2, outline, z0, z1, mat, **attr):
    """`outline` is a list of ((K,2), z) rings in the fastener's own plane."""
    Vs, ks = [], None
    for (P, z) in outline:
        Vs.append(o[None, :] + a[None, :] * z
                  + e1[None, :] * P[:, 0][:, None]
                  + e2[None, :] * P[:, 1][:, None])
        ks = len(P)
    V = np.concatenate(Vs)
    q = ring_faces(len(outline), ks, closed=True)
    ng = [list(range(ks - 1, -1, -1)),
          list(range((len(outline) - 1) * ks, len(outline) * ks))]
    return acc.solid(V, quads=q, ngons=ng, mat=mat, **attr)


def thread_rings(d, pitch, z0, z1, nseg, depth_f=0.61, turns_res=8):
    """A REAL helix, not a stack of rings: r(theta, z) follows the lead.

    ISO metric thread depth is 0.6134 * pitch; the crest is flattened at
    pitch/8 and the root rounded.  At 1.75 mm pitch this is 2.5 px per turn —
    right at the edge of resolution, which is exactly where a real bolt's
    shank lives: you cannot count the turns but you can see it is threaded.
    """
    H = depth_f * pitch
    n = max(4, int(math.ceil(abs(z1 - z0) / (pitch / turns_res))))
    z = np.linspace(z0, z1, n + 1)
    ang = np.arange(nseg) * (2.0 * math.pi / nseg)
    ph = (z[:, None] / pitch) - (ang[None, :] / (2.0 * math.pi))
    f = ph - np.floor(ph)
    # a trapezoid: flat crest 1/8, flanks, rounded root
    prof = np.clip(1.0 - np.abs((f - 0.5) * 2.0) * 1.34, 0.0, 1.0)
    prof = prof ** 0.72
    r = (d * 0.5) - H * (1.0 - prof)
    return z, r


def bolt(acc, o, axis, ref, spec, grip, lod, protrude=None, nut=True,
         washer=True, mat=0, seed=0, ang0=None, **attr):
    """A whole fastener: hex head, washer, threaded shank, nut, stick-out."""
    o, a, e1, e2 = _fr(o, axis, ref)
    L = LOD_SPEC[lod]
    nseg = L["bolt"]
    d = spec["d"]
    af = spec["af"]
    hh = spec["hh"]
    wt = spec["wt"] if washer else 0.0
    phase = (ang0 if ang0 is not None else h01(seed, 3) * math.pi / 3.0)
    # --- head: the underside washer face, the flats, the 30 deg chamfer -----
    ch = af * 0.075
    hexo = hexagon(af, n_flat=(3 if lod >= 2 else 1))
    hexc = hexagon(af, n_flat=(3 if lod >= 2 else 1), chamfer=-ch)
    rot = np.array([[math.cos(phase), -math.sin(phase)],
                    [math.sin(phase), math.cos(phase)]])
    hexo = hexo @ rot.T
    hexc = hexc @ rot.T
    # the bearing surface under a hex head is a WASHER FACE: a shallow raised
    # boss, not the full flat of the hexagon.  It is 0.6 mm and it is the line
    # that separates the head from the washer at 27 px across.
    rings = [(hexo * 0.955, wt), (hexo, wt + 0.0006),
             (hexo, wt + hh - ch), (hexc, wt + hh)]
    if lod < 2:
        rings = [(hexo, wt), (hexo, wt + hh - ch), (hexc, wt + hh)]
    _emit_prism(acc, o, a, e1, e2, rings, wt, wt + hh, mat,
                kind=K_BOLT, edge=1.0, **attr)
    # --- washer -------------------------------------------------------------
    if washer:
        _emit_rev(acc, o, a, e1, e2, washer_rings(spec["hole"], spec["wo"], wt),
                  max(nseg, 12), mat, cap=(False, False),
                  kind=K_BOLT, edge=0.85, **attr)
    # --- shank + thread -----------------------------------------------------
    zs = -grip
    ze = wt
    if L["thread"]:
        # plain shank under the head, thread the rest: that is how a
        # part-threaded bolt is made and the transition is visible
        zt = min(ze - 0.0, zs + max(0.006, grip * 0.34))
        z, r = thread_rings(d, spec["pitch"], zs - (protrude or 0.0), zt, nseg)
        ang = np.arange(nseg) * (2.0 * math.pi / nseg)
        V = (o[None, None, :] + a[None, None, :] * z[:, None, None]
             + e1[None, None, :] * (r * np.cos(ang)[None, :])[:, :, None]
             + e2[None, None, :] * (r * np.sin(ang)[None, :])[:, :, None])
        acc.add(V.reshape(-1, 3), quads=ring_faces(len(z), nseg, True), mat=mat,
                kind=K_BOLT, bare=0.25, **attr)
        _emit_rev(acc, o, a, e1, e2, [(0.0, zt), (d * 0.5, zt),
                                      (d * 0.5, ze), (0.0, ze)], nseg, mat,
                  kind=K_BOLT, **attr)
        # the cut end of the thread, chamfered as rolled
        _emit_rev(acc, o, a, e1, e2,
                  [(0.0, zs - (protrude or 0.0) - 0.0009),
                   (d * 0.40, zs - (protrude or 0.0) - 0.0009),
                   (d * 0.48, zs - (protrude or 0.0))], nseg, mat,
                  kind=K_BOLT, bare=0.6, edge=1.0, **attr)
    else:
        _emit_rev(acc, o, a, e1, e2,
                  [(0.0, zs - (protrude or 0.0)), (d * 0.47, zs - (protrude or 0.0)),
                   (d * 0.5, zs - (protrude or 0.0) + 0.001),
                   (d * 0.5, ze), (0.0, ze)], nseg, mat,
                  kind=K_BOLT, **attr)
    # --- nut ----------------------------------------------------------------
    if nut:
        nh = spec["nut"]
        z0 = zs
        z1 = zs + nh
        nch = af * 0.08
        hxn = hexagon(af, n_flat=(3 if lod >= 2 else 1)) @ rot.T
        hxc = hexagon(af, n_flat=(3 if lod >= 2 else 1), chamfer=-nch) @ rot.T
        _emit_prism(acc, o, a, e1, e2,
                    [(hxc, z0), (hxn, z0 + nch), (hxn, z1 - nch), (hxc, z1)],
                    z0, z1, mat, kind=K_NUT, edge=1.0, **attr)


def hd_bolt(acc, o, axis, ref, spec, above, lod, mat=0, seed=0, **attr):
    """A cast-in holding-down bolt: threaded stud, a levelling nut, the plate,
    a washer and the top nut, with the thread running out above it.  The
    LEVELLING NUT is the tell that this is a base plate and not a slab."""
    o, a, e1, e2 = _fr(o, axis, ref)
    L = LOD_SPEC[lod]
    nseg = L["bolt"]
    d = spec["d"]
    if L["thread"]:
        z, r = thread_rings(d, spec["pitch"], -0.035, above, nseg)
        ang = np.arange(nseg) * (2.0 * math.pi / nseg)
        V = (o[None, None, :] + a[None, None, :] * z[:, None, None]
             + e1[None, None, :] * (r * np.cos(ang)[None, :])[:, :, None]
             + e2[None, None, :] * (r * np.sin(ang)[None, :])[:, :, None])
        acc.add(V.reshape(-1, 3), quads=ring_faces(len(z), nseg, True),
                mat=mat, kind=K_BOLT, bare=0.3, **attr)
    else:
        _emit_rev(acc, o, a, e1, e2, [(0.0, -0.035), (d * 0.5, -0.035),
                                      (d * 0.5, above), (0.0, above)],
                  nseg, mat, kind=K_BOLT, **attr)
    _emit_rev(acc, o, a, e1, e2,
              [(0.0, above), (d * 0.46, above), (d * 0.5, above - 0.0012)],
              nseg, mat, kind=K_BOLT, bare=0.7, edge=1.0, **attr)
    return o, a, e1, e2


def hex_nut(acc, o, axis, ref, spec, z0, lod, mat=0, phase=0.0, **attr):
    o, a, e1, e2 = _fr(o, axis, ref)
    nh = spec["nut"]
    nch = spec["af"] * 0.08
    rot = np.array([[math.cos(phase), -math.sin(phase)],
                    [math.sin(phase), math.cos(phase)]])
    hxn = hexagon(spec["af"], n_flat=(3 if lod >= 2 else 1)) @ rot.T
    hxc = hexagon(spec["af"], n_flat=(3 if lod >= 2 else 1),
                  chamfer=-nch) @ rot.T
    _emit_prism(acc, o, a, e1, e2,
                [(hxc, z0), (hxn, z0 + nch), (hxn, z0 + nh - nch),
                 (hxc, z0 + nh)], z0, z0 + nh, mat, kind=K_NUT, edge=1.0, **attr)


