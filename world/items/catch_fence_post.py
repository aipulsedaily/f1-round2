def _flange_face(p, sec, z, u, out=False):
    """A point on a flange OUTER face at height z, offset u across the flange.
    `out=False` is the TRACK side, which is the side the fabric bears on."""
    v = (0.5 * sec.D) * (1.0 if out else -1.0)
    return local_point(p, [z], u, v)[0]


def build_cleats(acc, p, lod, mat=0, mat_bolt=0):
    """The clamp bars that grip the fabric, and their fasteners.

    A debris fence panel is not welded to the post, it is TRAPPED: a 60 x 8
    flat bar laid across the fabric and pulled down onto the flange by two
    M12s.  The bar bends slightly over the wire it is clamping, the bolts are
    not all at the same clock angle, and the nut is INSIDE the section where
    nobody ever painted it.  All three are here.
    """
    sec = p.sec
    hollow = (sec.kind == "SHS")
    half = 0.5 * sec.B
    L = LOD_SPEC[lod]
    for i, cz in enumerate(p.cleat_z):
        sd = p.seed * 13 + i * 101
        bx = min(half - 0.020, 0.046)
        # the bar
        lu = half + CLEAT_L_MARGIN
        Cc, eu, ev = post_frames(p, np.array([cz]))
        o = Cc[0]
        nrm = -ev[0]                       # toward the track
        face = o + nrm * (0.5 * sec.D)
        # fabric thickness the bar rides over: 2 wires of 4.0 mm
        fab = 0.0080 if not chance(0.10, sd, 3) else 0.0
        ctr = face + nrm * (fab + CLEAT_T * 0.5)
        tilt = math.radians(rnd(-1.4, 1.4, sd, 5))
        eu2 = eu[0] * math.cos(tilt) + np.array([0, 0, 1.0]) * math.sin(tilt)
        ey2 = unit(np.cross(nrm, eu2)) * (CLEAT_W * 0.5)
        if lod <= 0:
            # at > 130 m a 60 x 8 bar is 0.6 px wide.  A radiused plate there
            # is 160 triangles spent on nothing; a box is 12 and reads the same.
            box_solid(acc, ctr, eu2 * lu, ey2, nrm * (CLEAT_T * 0.5), mat=mat,
                      kind=K_CLEAT, hz=cz, expo=1.0, edge=0.5, crev=0.15)
            continue
        plate_solid(acc, ctr, eu2 * lu, ey2,
                    nrm * (CLEAT_T * 0.5), rc=0.0035,
                    nseg=(3 if lod >= 3 else 1), mat=mat,
                    kind=K_CLEAT, hz=cz, expo=1.0, edge=0.5,
                    crev=0.15, bare=0.25 * h01(sd, 7))
        # the two bolts
        for s in (-1.0, 1.0):
            bo = ctr + eu2 * (s * bx)
            # THE GRIP IS THE STACK, exactly: bar + fabric + flange.  On a
            # hollow section the bolt goes right through both walls, which is
            # why an SHS post has a nut on the far face and an H does not.
            grip = (fab + CLEAT_T + sec.B) if hollow \
                else (fab + CLEAT_T + sec.tf)
            bolt(acc, bo + nrm * (CLEAT_T * 0.5), nrm, eu2, M12,
                 grip, lod, protrude=rnd(0.002, 0.008, sd, 11 + s),
                 nut=True, washer=True, mat=mat_bolt, seed=int(sd + s * 7),
                 hz=cz, expo=1.0, crev=0.25)


def build_head(acc, p, lod, mat=0):
    """The bolted splice the CRANKED HEAD lands on.

    catch_fence_cranked_head is a separate 0.9 m member.  Real practice bolts
    it to the post through the flanges, so the holes are drilled at the mill
    and they are drilled whether or not the head is fitted yet.  This module
    owns the holes; that module owns the member and the bolts.
    """
    sec = p.sec
    cut = []
    if sec.kind == "SHS":
        # A HOLLOW SECTION DOES NOT TAKE A FLANGE SPLICE.  It takes a SOCKET:
        # the head is a smaller SHS dropped into the bore and pinned through
        # both walls.  The first version returned [] here, which left 77 posts
        # with nothing at all for catch_fence_cranked_head to fix to -- an
        # interface that is silently empty for 11 % of the population is worse
        # than one that is missing, because the dependant will not notice.
        for zr in HEAD_ROWS:
            Cc, eu, ev = post_frames(p, np.array([zr]))
            n = eu[0]
            o = Cc[0] - n * (0.5 * sec.B + 0.006)
            cut.append(dict(o=o, a=n, r=HEAD_HOLE_D * 0.5,
                            depth=sec.B + 0.012))
        return cut
    for zr in HEAD_ROWS:
        for uu in (-HEAD_COLS, HEAD_COLS):
            for out in (False, True):
                pt = _flange_face(p, sec, zr, uu, out=out)
                Cc, eu, ev = post_frames(p, np.array([zr]))
                n = ev[0] * (1.0 if out else -1.0)
                cut.append(dict(o=pt - n * 0.004, a=n, r=HEAD_HOLE_D * 0.5,
                                depth=sec.tf + 0.010))
    return cut


def build_base(acc, p, lod, mat=0, mat_bolt=0, mat_conc=0):
    """Three different bases, because three different things happened here.

    `plate`     a 300 x 300 x 16 plate, fillet-welded all round, on four cast-in
                M20s with a LEVELLING NUT under the plate and a grout gap.  This
                is what a post standing on the pit-exit apron gets, because you
                do not dig a 1.2 m hole in a concrete apron.
    `concrete`  the member runs 1.2 m into a poured pier.  Nothing above ground
                is mine; the pier and the disturbed ring belong to
                catch_fence_base_collar and this module publishes them.
    `driven`    driven with a hydraulic post driver.  The steel is scored where
                it went through the fill, the plumb error is 2.1x, and the top
                took the drive cap: a slight mushroom at the head.
    """
    sec = p.sec
    L = LOD_SPEC[lod]
    if p.base_kind != "plate":
        # a soil-contact band: bitumen-wrapped on some, bare on others.  It is
        # geometry only in that the wrap stands 0.6 mm proud.
        if lod >= 2 and chance(0.45, p.seed, 457):
            zsb = np.linspace(-0.12, 0.09, 8)
            loops = section_loops(sec, min(lod, 2))
            P2, N2, TG, A2 = loops[0]
            Cc, eu, ev = post_frames(p, zsb)
            bump = 0.0006 * np.exp(-0.5 * ((zsb + 0.015) / 0.075) ** 2)
            Pd = P2[None, :, :] + N2[None, :, :] * bump[:, None, None]
            V = (Cc[:, None, :] + eu[:, None, :] * Pd[:, :, 0][:, :, None]
                 + ev[:, None, :] * Pd[:, :, 1][:, :, None])
            acc.add(V.reshape(-1, 3),
                    quads=ring_faces(len(zsb), len(P2), True), mat=mat,
                    kind=K_STEEL, hz=np.tile(zsb[:, None], (1, len(P2))).ravel(),
                    bare=0.75, crev=0.6, expo=0.3, edge=0.2)
        return []
    # --- the plated base ----------------------------------------------------
    hw = 0.150
    th = BASE_PLATE_T * 0.5          # half of the 16 mm plate
    Cc, eu, ev = post_frames(p, np.array([0.0]))
    o = Cc[0] + np.array([0.0, 0.0, 0.0])
    ex, ey = eu[0], ev[0]
    ez = np.array([0.0, 0.0, 1.0])
    plate_solid(acc, o + ez * th, ex * hw, ey * hw, ez * th, rc=0.006,
                nseg=(4 if lod >= 3 else 1), mat=mat, kind=K_PLATE, hz=0.0,
                expo=0.8, edge=0.4, crev=0.25, bare=0.15)
    # the fillet weld: eight straight runs round the section footprint
    if lod >= 1:
        loops = section_loops(sec, min(lod, 2))
        P2, N2, TG, A2 = loops[0]
        n = len(P2)
        step = max(1, n // (48 if lod >= 3 else 20))
        idx = np.arange(0, n, step)
        pts = (o + ez * (2 * th)
               + ex[None, :] * P2[idx, 0][:, None]
               + ey[None, :] * P2[idx, 1][:, None])
        pts = np.vstack([pts, pts[:1]])
        nn = (ex[None, :] * N2[idx, 0][:, None] + ey[None, :] * N2[idx, 1][:, None])
        nn = np.vstack([nn, nn[:1]])
        # 8 mm leg: the code minimum for a 9.4 mm flange, and 11 px at the
        # filmed distance.  6 mm was inside the plate's own edge break and
        # disappeared in the first base render.
        leg = 0.008
        for i in range(len(pts) - 1):
            fillet_weld(acc, pts[i:i + 2], leg, nn[i], ez, lod, mat=mat,
                        seed=p.seed + i, hz=0.0, crev=0.85, expo=0.5)
    # four holding-down bolts
    for sx in (-1.0, 1.0):
        for sy in (-1.0, 1.0):
            bo = o + ex * (sx * 0.108) + ey * (sy * 0.108)
            hex_nut(acc, bo, ez, ex, M20, -0.016, lod, mat=mat_bolt,
                    phase=h01(p.seed, 461 + int(sx) * 3 + int(sy)),
                    hz=0.0, crev=0.7)
            hd_bolt(acc, bo, ez, ex, M20, 2 * th + M20["wt"] + M20["nut"]
                    + rnd(0.004, 0.014, p.seed, 463), lod, mat=mat_bolt,
                    seed=p.seed + 11, hz=0.0, expo=0.7)
            wr = [(r, z + 2 * th) for (r, z) in
                  washer_rings(M20["hole"], M20["wo"], M20["wt"])]
            _emit_rev(acc, *_fr(bo, ez, ex), rings=wr,
                      nseg=max(L["wash"], 8), mat=mat_bolt, cap=(False, False),
                      kind=K_BOLT, hz=0.0, edge=0.7)
            hex_nut(acc, bo, ez, ex, M20, 2 * th + M20["wt"], lod,
                    mat=mat_bolt, phase=h01(p.seed, 467 + int(sx)),
                    hz=0.0, expo=0.8)
    return []


def build_raker(acc, p, lod, mat=0, mat_bolt=0):
    """The stay.  48.3 CHS with both ends PRESSED FLAT and drilled — which is
    how a fabricator makes one, and which is a shape no primitive has."""
    if not p.raker:
        return
    L = LOD_SPEC[lod]
    sec = p.sec
    zt = min(p.raker_z, p.stand_h - 0.35)
    Cc, eu, ev = post_frames(p, np.array([zt]))
    top = Cc[0] + ev[0] * (0.5 * sec.D + 0.012)
    reach = p.raker_reach
    foot = np.array([p.bow_t * 0.2, reach, -0.12])
    axis = unit(foot - top)
    ln = float(np.linalg.norm(foot - top))
    n = max(6, int(ln / 0.09) if lod >= 2 else 4)
    path = np.linspace(top, foot, n)
    od, wall = 0.0483, 0.0032
    nseg = max(L["tube"], 6)
    t = np.linspace(0.0, 1.0, n)
    flat = np.exp(-((t / 0.075) ** 2)) + np.exp(-(((1 - t) / 0.075) ** 2))
    prof = np.zeros((n, nseg, 2))
    ca = np.cos(np.arange(nseg) * 2 * math.pi / nseg)
    sa = np.sin(np.arange(nseg) * 2 * math.pi / nseg)
    for i in range(n):
        f = min(1.0, flat[i])
        rx = od * 0.5 * (1.0 - 0.86 * f)
        ry = od * 0.5 * (1.0 + 0.30 * f)
        prof[i, :, 0] = ca * rx
        prof[i, :, 1] = sa * ry
    sweep_ring(acc, path, prof, mat=mat, caps=(True, True), close_prof=True,
               kind=K_TUBE, hz=zt * 0.5, expo=0.9, edge=0.25,
               crev=0.1, bare=0.1)
    # the cleat it bolts to, and the bolt
    if lod >= 1:
        ez = unit(np.cross(axis, eu[0]))
        plate_solid(acc, top + ev[0] * 0.006, eu[0] * 0.045, ez * 0.055,
                    ev[0] * 0.005, rc=0.004, nseg=2, mat=mat, kind=K_PLATE,
                    hz=zt, expo=0.9, edge=0.5)
        bolt(acc, top + ev[0] * 0.014, ev[0], eu[0], M16,
             0.032, lod, protrude=0.006, mat=mat_bolt, seed=p.seed + 23,
             hz=zt, expo=0.9)
        if lod >= 2:
            fillet_weld(acc, np.stack([top + eu[0] * -0.045 + ev[0] * 0.001,
                                       top + eu[0] * 0.045 + ev[0] * 0.001]),
                        0.005, ev[0], ez, lod, mat=mat, seed=p.seed + 29,
                        hz=zt, crev=0.8)
        # the foot cleat
        plate_solid(acc, foot - axis * 0.010,
                    unit(np.cross(axis, np.array([0, 0, 1.0]))) * 0.050,
                    unit(np.cross(axis, unit(np.cross(axis,
                                                      np.array([0, 0, 1.0])))))
                    * 0.045, axis * 0.005, rc=0.004, nseg=2, mat=mat,
                    kind=K_PLATE, hz=0.0, expo=0.6, edge=0.5, crev=0.4)


def build_splice(acc, p, lod, mat=0, mat_bolt=0):
    """A repaired post: the top was cut out and a new length bolted in with
    flange splice plates.  1.6 % of the population, and it is the single most
    'this circuit has a history' object on the fence."""
    if not p.splice_z:
        return
    sec = p.sec
    if sec.kind == "SHS":
        return
    z = p.splice_z
    for out in (False, True):
        for row in (-1, 1):
            pass
        Cc, eu, ev = post_frames(p, np.array([z]))
        n = ev[0] * (1.0 if out else -1.0)
        ctr = Cc[0] + n * (0.5 * sec.D + 0.005)
        plate_solid(acc, ctr, eu[0] * (sec.B * 0.44), np.array([0, 0, 0.115]),
                    n * 0.005, rc=0.005, nseg=(3 if lod >= 3 else 1), mat=mat,
                    kind=K_PLATE, hz=z, expo=0.9, edge=0.5, bare=0.3)
        if lod >= 1:
            for su in (-1.0, 1.0):
                for sz in (-1.0, 1.0):
                    bo = ctr + eu[0] * (su * sec.B * 0.28) \
                        + np.array([0, 0, sz * 0.072])
                    bolt(acc, bo + n * 0.005, n, eu[0], M16,
                         0.010 + sec.tf, lod, protrude=0.005,
                         mat=mat_bolt, seed=int(p.seed + su * 3 + sz * 5),
                         hz=z, expo=0.9)


def build_tag(acc, p, lod, mat=0):
    """The number tag.  Every post on a circuit is numbered, and the number is
    DIFFERENT ON EVERY POST — which makes this the one feature that cannot be
    faked by instancing."""
    L = LOD_SPEC[lod]
    if not L["tag"]:
        return
    sec = p.sec
    z = p.tag_z
    Cc, eu, ev = post_frames(p, np.array([z]))
    n = -ev[0]                                  # track side, so it can be read
    u = rnd(-0.030, 0.030, p.seed, 471)
    ctr = Cc[0] + eu[0] * u + n * (0.5 * sec.D + 0.0016)
    # WHICH WAY IS LEFT.  Text is laid out in the (ex, ez) plane of a face
    # whose outward normal is n, so a reader standing in front of it looks
    # along -n and their right hand points along cross(n, up), NOT along the
    # section's own +u.  Using +u put "3129" on the tag BACKWARDS, which the
    # first CAM_TAG render showed in 8 mm characters.
    up0 = np.array([0.0, 0.0, 1.0])
    ex0 = unit(np.cross(n, up0))
    tilt = math.radians(rnd(-7.0, 7.0, p.seed, 473))
    ex = ex0 * math.cos(tilt) + up0 * math.sin(tilt)
    ez = up0 * math.cos(tilt) - ex0 * math.sin(tilt)
    txt = "%d" % p.tag_no
    if L["tag"] == "stamp":
        stamped_plate(acc, ctr, ex, ez, n, 0.030, 0.018, 0.0012, txt,
                      0.0090, 0.00115, 0.00042, mat=mat, seed=p.seed,
                      hz=z, expo=1.0, edge=0.4, crev=0.2)
    else:
        plate_solid(acc, ctr, ex * 0.030, ez * 0.018, n * 0.0006, rc=0.003,
                    nseg=1, mat=mat, kind=K_TAG, hz=z, expo=1.0, edge=0.4)
        st, adv = text_strokes(txt, 0.0090, tracking=0.26)
        stroke_slabs(acc, [s - np.array([adv * 0.5, 0.0045]) for s in st],
                     ctr + n * 0.0006, ex, ez, n, 0.0022, 0.0006, mat=mat,
                     seed=p.seed, hz=z, expo=1.0)
    # the wire that holds it on
    if lod >= 3:
        a = ctr + ex * 0.0245 + ez * 0.010
        b = Cc[0] + eu[0] * (u + 0.030) + n * (0.5 * sec.D - 0.004)
        path = np.linspace(a, b, 6)
        path[2:4, :] += n * 0.004
        pr, _ = circle(6, 0.0009)
        sweep_ring(acc, path, pr, mat=mat, caps=(True, True),
                   kind=K_TUBE, hz=z, bare=0.4, expo=1.0, edge=0.3)


def build_mark(acc, p, lod, mat=0):
    """The rolled-in mill mark on the web: raised metal, 0.9 mm proud.

    Real hot-rolled sections carry the mill, the serial and the grade rolled
    into the web by the finishing stand.  It is 23 px tall at the filmed
    distance and it is the detail that says this is a ROLLED section that came
    from somewhere, rather than a box that was modelled.
    """
    if not LOD_SPEC[lod]["mark"] or p.sec.kind == "SHS":
        return
    sec = p.sec
    z = rnd(2.35, 3.30, p.seed, 481)
    side = 1.0 if chance(0.5, p.seed, 483) else -1.0
    Cc, eu, ev = post_frames(p, np.array([z]))
    n = eu[0] * side                       # the web faces along the fence
    ctr = Cc[0] + n * (0.5 * sec.tw + 0.0001)
    ez = np.array([0.0, 0.0, 1.0])
    ex = unit(np.cross(n, ez))          # the reader's right, not the section's
    h = 0.014
    for k, txt in enumerate(("NORDVAL ACIERS", sec.name.replace(" ", " "),
                             sec.grade)):
        st, adv = text_strokes(txt, h, tracking=0.24)
        base = ctr + ez * (-k * (h * 1.9)) - ex * 0.0
        stroke_slabs(acc, [s - np.array([adv * 0.5, h * 0.5]) for s in st],
                     base, ex, ez, n, 0.0022, 0.0009, mat=mat, seed=p.seed + k,
                     hz=z - k * h * 1.9, expo=0.25, crev=0.55, edge=0.6)


def build_cap(acc, p, lod, mat=0):
    """A cap plate on a third of them, welded on so water cannot sit in the
    section.  The other two thirds are open, which is why they weep rust down
    the web — and that is in the shader, keyed off this being absent."""
    if not p.cap_plate:
        return
    sec = p.sec
    Cc, eu, ev = post_frames(p, np.array([p.stand_h]))
    o = Cc[0]
    hu = sec.B * 0.5 + 0.004
    hv = sec.D * 0.5 + 0.004
    ez = unit(np.cross(eu[0], ev[0]))
    plate_solid(acc, o + ez * 0.004, eu[0] * hu, ev[0] * hv, ez * 0.004,
                rc=0.005, nseg=(3 if lod >= 3 else 1), mat=mat, kind=K_PLATE,
                hz=p.stand_h, expo=1.0, edge=0.5, crev=0.1)
    if lod >= 2:
        loops = section_loops(sec, min(lod, 2))
        P2, N2, TG, A2 = loops[0]
        step = max(1, len(P2) // (40 if lod >= 3 else 16))
        idx = np.arange(0, len(P2), step)
        pts = (o + eu[0][None, :] * P2[idx, 0][:, None]
               + ev[0][None, :] * P2[idx, 1][:, None])
        pts = np.vstack([pts, pts[:1]])
        nn = (eu[0][None, :] * N2[idx, 0][:, None]
              + ev[0][None, :] * N2[idx, 1][:, None])
        nn = np.vstack([nn, nn[:1]])
        for i in range(len(pts) - 1):
            fillet_weld(acc, pts[i:i + 2], 0.004, nn[i], -ez, lod, mat=mat,
                        seed=p.seed + 41 + i, hz=p.stand_h, crev=0.8, expo=0.9)


