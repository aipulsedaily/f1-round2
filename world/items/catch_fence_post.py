# Every number in this module comes from a hash of integers.  Nothing is drawn
# from a global RNG, so a post is the same post whether the whole circuit is
# built or just one of them.

_U32 = np.uint32


def hash01(*keys):
    arrs = [np.asarray(k) for k in keys]
    shape = np.broadcast(*arrs).shape if len(arrs) > 1 else arrs[0].shape
    h = np.full(shape, _U32(2166136261), dtype=np.uint32)
    with np.errstate(over="ignore"):
        for kk in arrs:
            k = np.rint(kk).astype(np.int64) if kk.dtype.kind == "f" \
                else kk.astype(np.int64)
            k = (k & 0xFFFFFFFF).astype(np.uint32)
            h = (h ^ k) * _U32(16777619)
            h = h ^ (h >> _U32(13))
            h = h * _U32(2654435761)
            h = h ^ (h >> _U32(16))
    return (h & _U32(0xFFFFFF)).astype(np.float64) / 16777215.0


def h01(*keys):
    return float(hash01(*[np.int64(k) for k in keys]))


def rnd(lo, hi, *keys):
    return lo + (hi - lo) * h01(*keys)


def rint(lo, hi, *keys):
    return int(lo + math.floor((hi - lo + 1) * h01(*keys) * 0.9999999))


def chance(p, *keys):
    return h01(*keys) < p


def pick(seq, *keys):
    return seq[min(len(seq) - 1, int(h01(*keys) * len(seq)))]


def gauss(sd, *keys):
    """Box-Muller from two hashes.  Real erection error is normal, not uniform;
    a uniform lean puts as many posts at 2.4 deg as at 0.1 deg and the line
    reads as a picket fence that has been shuffled."""
    u1 = max(1e-9, h01(*keys, 101))
    u2 = h01(*keys, 211)
    return sd * math.sqrt(-2.0 * math.log(u1)) * math.cos(2.0 * math.pi * u2)


def _s5(t):
    return t * t * t * (t * (t * 6.0 - 15.0) + 10.0)


def n1(x, seed=0):
    x = np.asarray(x, float)
    i = np.floor(x).astype(np.int64)
    f = x - i
    a = hash01(i, np.full_like(i, seed))
    b = hash01(i + 1, np.full_like(i, seed))
    return a + (b - a) * _s5(f)


def fbm1(x, seed=0, oct=4, gain=0.5, lac=2.07):
    x = np.asarray(x, float)
    tot = np.zeros_like(x)
    amp, nrm, frq = 1.0, 0.0, 1.0
    for o in range(oct):
        tot = tot + amp * n1(x * frq, seed * 131 + o * 17)
        nrm += amp
        amp *= gain
        frq *= lac
    return tot / nrm


def clamp01(a):
    return np.clip(a, 0.0, 1.0)


def sstep(a, b, x):
    return _s5(np.clip((np.asarray(x, float) - a) / max(1e-9, b - a), 0.0, 1.0))


def unit(v):
    v = np.asarray(v, float)
    n = float(np.linalg.norm(v))
    return v / (n if n > 1e-12 else 1.0)


