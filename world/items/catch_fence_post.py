def text_strokes(txt, h, tracking=0.22):
    """-> (list of (P (n,2)) polylines in metres, total advance)."""
    out, x = [], 0.0
    w = h * 0.62
    for ch in txt:
        g = GLYPH.get(ch, GLYPH.get(ch.upper(), GLYPH[" "]))
        aw = ADV.get(ch, 1.0) * w
        for s in g:
            p = s.copy()
            p[:, 0] = p[:, 0] * aw + x
            p[:, 1] = p[:, 1] * h
            out.append(p)
        x += aw + tracking * w
    return out, max(0.0, x - tracking * w)


def stroke_slabs(acc, strokes, o, eu, ev, ew, sw, relief, mat=0, seed=0,
                 nround=3, **attr):
    """Raised strokes standing `relief` off a face — a ROLLED-IN mark.

    Each segment becomes a capsule-section prism.  Overlaps at the joints are
    left alone on purpose: rolled metal piles up where two strokes meet and a
    booleaned-clean junction is the wrong read.
    """
    o = np.asarray(o, float)
    for P in strokes:
        for i in range(len(P) - 1):
            a2, b2 = P[i], P[i + 1]
            d = b2 - a2
            ln = float(np.linalg.norm(d))
            if ln < 1e-6:
                continue
            d = d / ln
            n2 = np.array([-d[1], d[0]])
            ring = []
            for k in range(nround + 1):
                t = k / float(nround) * math.pi
                ring.append(b2 + (d * math.sin(t) + n2 * math.cos(t)) * sw * .5)
            for k in range(nround + 1):
                t = k / float(nround) * math.pi
                # ... and back down the OTHER side.  Getting this half's sign
                # wrong makes the capsule outline cross itself and every glyph
                # renders as a bowtie.  It did, once.
                ring.append(a2 - (d * math.sin(t) + n2 * math.cos(t)) * sw * .5)
            ring = np.array(ring)
            V = []
            for (RR, hh) in ((ring, 0.0), (ring, relief * 0.62),
                             (_shrink2(ring, sw * 0.16), relief)):
                V.append(o[None, :] + eu[None, :] * RR[:, 0][:, None]
                         + ev[None, :] * RR[:, 1][:, None] + ew[None, :] * hh)
            V = np.concatenate(V)
            k2 = len(ring)
            q = ring_faces(3, k2, closed=True)
            ng = [list(range(k2 - 1, -1, -1)), list(range(2 * k2, 3 * k2))]
            attr.setdefault("kind", K_MARK)
            attr.setdefault("edge", 0.8)
            acc.solid(V, quads=q, ngons=ng, mat=mat, **attr)


def _shrink2(P, dr):
    ctr = P.mean(axis=0)
    d = P - ctr
    n = np.maximum(np.linalg.norm(d, axis=1)[:, None], 1e-9)
    return ctr + d * np.maximum(0.0, (n - dr)) / n


def _seg_dist(Q, P):
    """Min distance from points Q (N,2) to a polyline P (M,2)."""
    best = np.full(len(Q), 1e9)
    for i in range(len(P) - 1):
        a2, b2 = P[i], P[i + 1]
        d = b2 - a2
        L2 = float(d @ d)
        if L2 < 1e-14:
            best = np.minimum(best, np.linalg.norm(Q - a2, axis=1))
            continue
        t = np.clip(((Q - a2) @ d) / L2, 0.0, 1.0)
        pr = a2[None, :] + t[:, None] * d[None, :]
        best = np.minimum(best, np.linalg.norm(Q - pr, axis=1))
    return best


def stamped_plate(acc, o, eu, ev, ew, hw, hh, thick, txt, tsize, depth,
                  cell, mat=0, hole=None, seed=0, sw=0.0022, **attr):
    """A plate with DIE-STAMPED characters: a fine grid displaced downward.

    A stamp does not cut, it displaces — so the metal rises in a lip around
    each stroke, and the zinc cracks white along the lip.  Both of those are
    in here: the lip is geometry (`+depth*0.22` just outside the stroke) and
    the cracked zinc is what the `bare` attribute drives in the shader.
    """
    nu = max(4, int(round(2 * hw / cell)) + 1)
    nv = max(4, int(round(2 * hh / cell)) + 1)
    gu = np.linspace(-hw, hw, nu)
    gv = np.linspace(-hh, hh, nv)
    U, Vv = np.meshgrid(gu, gv, indexing="ij")
    Q = np.stack([U.ravel(), Vv.ravel()], axis=1)
    strokes, adv = text_strokes(txt, tsize, tracking=0.26)
    off = np.array([-adv * 0.5, -tsize * 0.5])
    d = np.full(len(Q), 1e9)
    for P in strokes:
        d = np.minimum(d, _seg_dist(Q, P + off))
    inside = clamp01((sw * 0.5 + cell * 0.5 - d) / max(cell, 1e-9))
    lip = np.exp(-((d - sw * 0.5 - cell * 0.9) / (cell * 1.6)) ** 2) \
        * (d > sw * 0.5)
    dz = -depth * inside + depth * 0.20 * lip
    # rounded plate corners: fold the grid in at the four corners
    rc = min(hw, hh) * 0.24
    cu = np.maximum(np.abs(Q[:, 0]) - (hw - rc), 0.0)
    cv = np.maximum(np.abs(Q[:, 1]) - (hh - rc), 0.0)
    over = np.sqrt(cu ** 2 + cv ** 2)
    k = np.where(over > 1e-9, np.minimum(1.0, rc / np.maximum(over, 1e-9)), 1.0)
    Qc = Q.copy()
    Qc[:, 0] = np.sign(Q[:, 0]) * (np.minimum(np.abs(Q[:, 0]), hw - rc)
                                   + cu * k)
    Qc[:, 1] = np.sign(Q[:, 1]) * (np.minimum(np.abs(Q[:, 1]), hh - rc)
                                   + cv * k)
    if hole is not None:
        hx, hy, hr = hole
        dh = np.linalg.norm(Qc - np.array([hx, hy]), axis=1)
        push = np.clip((hr + cell * 1.2 - dh) / max(cell, 1e-9), 0.0, 1.0)
        dirn = (Qc - np.array([hx, hy])) / np.maximum(dh, 1e-9)[:, None]
        Qc = Qc + dirn * (push * (hr + cell * 1.2 - dh))[:, None] * 0.0
    o = np.asarray(o, float)
    front = (o[None, :] + eu[None, :] * Qc[:, 0][:, None]
             + ev[None, :] * Qc[:, 1][:, None]
             + ew[None, :] * (thick * 0.5 + dz)[:, None])
    back = (o[None, :] + eu[None, :] * Qc[:, 0][:, None]
            + ev[None, :] * Qc[:, 1][:, None]
            + ew[None, :] * (-thick * 0.5 + dz * 0.30)[:, None])
    nvert = nu * nv
    V = np.concatenate([front, back])
    qf = grid_quads(nu, nv)
    qb = grid_quads(nu, nv)[:, ::-1] + nvert
    # rim
    idx = np.arange(nvert).reshape(nu, nv)
    rim = np.concatenate([idx[0, :], idx[1:, -1], idx[-1, -2::-1],
                          idx[-2::-1, 0]])
    r1 = np.roll(rim, -1)
    qr = np.stack([rim, r1, r1 + nvert, rim + nvert], axis=1)
    stamped = np.concatenate([inside, inside])
    attr.pop("edge", None)
    attr.pop("bare", None)
    attr.pop("kind", None)
    acc.add(V, quads=np.concatenate([qf, qb, qr]), mat=mat, kind=K_TAG,
            bare=0.35 + 0.55 * stamped, edge=0.55 + 0.45 * stamped, **attr)


