def _arc_pts(c, r, a0, a1, step, concave=False):
    """Arc from a0 to a1 (radians) sampled at `step` chord length, endpoints
    included.  `concave` flips the outward normal for a root fillet."""
    sweep = abs(a1 - a0) * r
    n = max(2, int(math.ceil(sweep / max(step, 1e-6))) + 1)
    a = np.linspace(a0, a1, n)
    P = np.stack([c[0] + r * np.cos(a), c[1] + r * np.sin(a)], axis=1)
    N = np.stack([np.cos(a), np.sin(a)], axis=1)
    if concave:
        N = -N
    return P, N


def _line_pts(p0, p1, step):
    p0 = np.asarray(p0, float)
    p1 = np.asarray(p1, float)
    L = float(np.linalg.norm(p1 - p0))
    n = max(2, int(math.ceil(L / max(step, 1e-6))) + 1)
    t = np.linspace(0.0, 1.0, n)[:, None]
    P = p0[None, :] * (1 - t) + p1[None, :] * t
    d = unit(p1 - p0)
    nrm = np.array([d[1], -d[0]])
    return P, np.tile(nrm, (n, 1))


def _weld_chain(parts, close=True):
    """Concatenate (P, N, tag) segments, dropping duplicated join points."""
    Ps, Ns, Ts = [], [], []
    for i, (P, N, tg) in enumerate(parts):
        if i and len(Ps) and np.linalg.norm(P[0] - Ps[-1][-1]) < 1e-9:
            P, N = P[1:], N[1:]
        if len(P) == 0:
            continue
        Ps.append(P)
        Ns.append(N)
        Ts.append(np.full(len(P), tg, np.int32))
    P = np.concatenate(Ps)
    N = np.concatenate(Ns)
    T = np.concatenate(Ts)
    if close and np.linalg.norm(P[0] - P[-1]) < 1e-9:
        P, N, T = P[:-1], N[:-1], T[:-1]
    return P, N, T


def _orient_ccw(P, N, T):
    """Signed area positive => counter-clockwise => the normals as built point
    outward.  A flipped loop is a black post under a raking sun, so this is
    measured rather than assumed."""
    x, y = P[:, 0], P[:, 1]
    a = 0.5 * float(np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y))
    if a < 0.0:
        P, N, T = P[::-1].copy(), N[::-1].copy(), T[::-1].copy()
    return P, N, T


def _arc_len(P):
    d = np.linalg.norm(np.diff(np.vstack([P, P[:1]]), axis=0), axis=1)
    return np.concatenate([[0.0], np.cumsum(d)[:-1]])


def h_profile(sec, flat, fine):
    """Closed outline of a rolled H section: (P, N, tag), CCW, outward normals.

    Built as a half (u >= 0) from the top-flange centre round to the
    bottom-flange centre, then mirrored.  Sampling is NOT uniform: the flats
    take `flat` (9 mm at LOD 3, which is 13 px and quite enough for a plane)
    and every radius takes `fine` (1.3 mm, 1.9 px) because the radii are the
    only curved thing in the section and they are what the eye reads.
    """
    D, B, tw, tf, r, rt = sec.D, sec.B, sec.tw, sec.tf, sec.r, sec.rt
    hv, hu = 0.5 * D, 0.5 * B
    vi = hv - tf                      # flange inner face
    wv = vi - r                       # where the root fillet meets the web
    parts = []
    # a. flange outer, centre -> toe
    parts.append(_line_pts((0.0, hv), (hu - rt, hv), flat) + (T_FLANGE_OUT,))
    # b. toe corner, outer
    P, N = _arc_pts((hu - rt, hv - rt), rt, math.pi / 2, 0.0, fine)
    parts.append((P, N, T_TOE))
    # c. toe face
    parts.append(_line_pts((hu, hv - rt), (hu, vi + rt), fine * 2.0) + (T_TOE,))
    # d. toe corner, inner
    P, N = _arc_pts((hu - rt, vi + rt), rt, 0.0, -math.pi / 2, fine)
    parts.append((P, N, T_TOE))
    # e. flange inner face, toe -> root
    parts.append(_line_pts((hu - rt, vi), (tw * 0.5 + r, vi), flat)
                 + (T_FLANGE_IN,))
    # f. THE ROOT FILLET.  Concave: the centre of curvature is in the air.
    P, N = _arc_pts((tw * 0.5 + r, vi - r), r, math.pi / 2, math.pi, fine,
                    concave=True)
    parts.append((P, N, T_ROOT))
    # g. web face
    parts.append(_line_pts((tw * 0.5, wv), (tw * 0.5, -wv), flat) + (T_WEB,))
    # h. lower root fillet
    P, N = _arc_pts((tw * 0.5 + r, -wv), r, math.pi, 1.5 * math.pi, fine,
                    concave=True)
    parts.append((P, N, T_ROOT))
    # i. lower flange inner
    parts.append(_line_pts((tw * 0.5 + r, -vi), (hu - rt, -vi), flat)
                 + (T_FLANGE_IN,))
    # j. lower toe corner, inner
    P, N = _arc_pts((hu - rt, -vi - rt), rt, math.pi / 2, 0.0, fine)
    parts.append((P, N, T_TOE))
    # k. lower toe face
    parts.append(_line_pts((hu, -vi - rt), (hu, -hv + rt), fine * 2.0)
                 + (T_TOE,))
    # l. lower toe corner, outer
    P, N = _arc_pts((hu - rt, -hv + rt), rt, 0.0, -math.pi / 2, fine)
    parts.append((P, N, T_TOE))
    # m. lower flange outer, toe -> centre
    parts.append(_line_pts((hu - rt, -hv), (0.0, -hv), flat)
                 + (T_FLANGE_OUT,))
    P, N, T = _weld_chain(parts, close=False)
    # mirror the interior points (skip the two on u = 0)
    Pm = P[-2:0:-1].copy()
    Nm = N[-2:0:-1].copy()
    Tm = T[-2:0:-1].copy()
    Pm[:, 0] *= -1.0
    Nm[:, 0] *= -1.0
    P = np.vstack([P, Pm])
    N = np.vstack([N, Nm])
    T = np.concatenate([T, Tm])
    return _orient_ccw(P, N, T)


def _rounded_box(hu, hv, rc, flat, fine, tag):
    """A rectangle with radiused corners, CCW, outward normals."""
    parts = []
    parts.append(_line_pts((0.0, hv), (hu - rc, hv), flat) + (tag,))
    P, N = _arc_pts((hu - rc, hv - rc), rc, math.pi / 2, 0.0, fine)
    parts.append((P, N, tag))
    parts.append(_line_pts((hu, hv - rc), (hu, -hv + rc), flat) + (tag,))
    P, N = _arc_pts((hu - rc, -hv + rc), rc, 0.0, -math.pi / 2, fine)
    parts.append((P, N, tag))
    parts.append(_line_pts((hu - rc, -hv), (0.0, -hv), flat) + (tag,))
    P, N, T = _weld_chain(parts, close=False)
    Pm, Nm, Tm = P[-2:0:-1].copy(), N[-2:0:-1].copy(), T[-2:0:-1].copy()
    Pm[:, 0] *= -1.0
    Nm[:, 0] *= -1.0
    return _orient_ccw(np.vstack([P, Pm]), np.vstack([N, Nm]),
                       np.concatenate([T, Tm]))


def shs_profile(sec, flat, fine):
    """A square hollow section: TWO loops.  The bore is a real hole with a real
    wall, so the cut end shows 8 mm of steel and the inside is a place light
    does not reach — which is why it weathers differently and why the item
    gate sees a different topology here than on the four H sections."""
    hu = hv = 0.5 * sec.B
    out = _rounded_box(hu, hv, sec.ro, flat, fine, T_SHS_OUT)
    P, N, T = _rounded_box(hu - sec.t, hv - sec.t, sec.ri, flat * 1.4,
                           fine * 1.6, T_SHS_BORE)
    # the bore's outward normal points INTO the steel
    return [out, (P[::-1].copy(), -N[::-1].copy(), T[::-1].copy())]


