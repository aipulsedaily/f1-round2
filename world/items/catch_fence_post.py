def main():
    argv = sys.argv
    argv = argv[argv.index("--") + 1:] if "--" in argv else []
    ap = argparse.ArgumentParser()
    ap.add_argument("--test", action="store_true")
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--save", default=None)
    ap.add_argument("--limit", type=int, default=None)
    ap.add_argument("--samples", type=int, default=256)
    ap.add_argument("--interface", nargs="?", const=os.path.join(
        _HERE, "catch_fence_post_interface.json"), default=None)
    a = ap.parse_args(argv)

    if a.selftest or not (a.test or a.save or a.interface):
        selftest()
        if not a.test and not a.interface:
            return
    if a.interface:
        export_interface(a.interface)
        if not (a.test or a.save):
            return
    if not HAVE_BPY:
        raise SystemExit("REFUSING: --test needs Blender.")
    t0 = time.time()
    test_scene(samples=a.samples, limit=a.limit)
    if a.save:
        out = os.path.abspath(a.save)
        os.makedirs(os.path.dirname(out), exist_ok=True)
        rem = [i.filepath for i in bpy.data.images if i.source == "FILE"]
        if rem:
            raise SystemExit("REFUSING TO SAVE: external images %s" % rem)
        bpy.ops.wm.save_as_mainfile(filepath=out, relative_remap=False,
                                    compress=False)
        log("saved %s (%.1f MB) in %.0f s"
            % (out, os.path.getsize(out) / 1048576.0, time.time() - t0))
    log("STAGE RESULT: CATCH_FENCE_POST_BUILT")


if __name__ == "__main__":
    main()
