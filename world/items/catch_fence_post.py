    print("   suppressed %d of %d slots for road intrusion (worst %.2f m in)"
          % (len(ri), len(post_sites(None, present_only=False)),
             ri[0]["intrusion_m"] if ri else 0.0))
    for d in ri[:4]:
        print("      side %+d pi %4d  s %7.1f -> projects to s %7.1f, "
              "%.2f m INSIDE the corridor  (barrier_offset %.1f m)"
              % (d["side"], d["pi"], d["s"], d["projected_s"],
                 d["intrusion_m"], d["barrier_offset_m"]))

    print("\n5. THE INTERFACE THE DEPENDANTS BUILD ON")
    cl = cleat_sites()
    sp = spans()
    hd = head_sites()
    co = collar_sites()
    re = run_ends()
    print("   cleat_sites()   %5d  (mesh grips)" % len(cl))
    print("   spans()         %5d  (manifest catch_fence_mesh_panel: 665)"
          % len(sp))
    print("   head_sites()    %5d  (manifest catch_fence_cranked_head: 690)"
          % len(hd))
    print("   collar_sites()  %5d  (manifest catch_fence_base_collar: 690)"
          % len(co))
    print("   run_ends()      %5d" % len(re))
    chk("spans() is near the manifest's 665 bays", 600 <= len(sp) <= 700,
        "%d" % len(sp))
    chk("head_sites() is one per post", len(hd) == len(ps))
    chk("collar_sites() is one per post", len(co) == len(ps))
    chk("every collar site has a finite ground z",
        all(np.isfinite(c["ground_z"]) for c in co))
    chk("head holes are drilled on the H sections",
        all(len(h["holes"]) == 8 for h in hd
            if h["connection"] == "flange_splice"))
    chk("EVERY post offers the head SOMETHING to fix to",
        all(h["holes"] for h in hd),
        "%d socketed, %d flange-spliced"
        % (sum(1 for h in hd if h["connection"] == "socket"),
           sum(1 for h in hd if h["connection"] == "flange_splice")))
    bl = np.array([s["length"] for s in sp])
    chk("no bay bridges a gap in the fence",
        float(np.percentile(bl, 99)) < SPAN_M * 1.10 and bl.max() < SPAN_M * 1.35,
        "p50 %.2f  p99 %.2f  max %.2f m over %d bays"
        % (np.percentile(bl, 50), np.percentile(bl, 99), bl.max(), len(bl)))
    lng = [s for s in sp if s["length"] > SPAN_M * 1.05
           or s["length"] < SPAN_M * 0.80]
    print("   %d bays are off the 8.00 m pitch by more than 5 %%; they are at "
          "the cusps where the barrier line doubles back:" % len(lng))
    for s in sorted(lng, key=lambda d: -abs(d["length"] - SPAN_M))[:3]:
        print("      side %+d pi %4d  s %7.1f  %.2f m" % (s["side"], s["pi"],
                                                          s["s"], s["length"]))

    print("\n6. THE HOLES ARE ACTUALLY HOLES")
    # R2-017 IN ONE CHECK.  This module claimed "real drilled holes with a real
    # bore wall" for three builds and two renders while the boolean was cutting
    # nothing at all: the cutters were built in the post's local frame and the
    # object had already been moved to (615, 476, -0.9), so they intersected
    # empty space.  It raised no error, because a boolean that removes nothing
    # is indistinguishable from one that was never asked to.
    #
    # So the check is not "did the punch run", it is "how many vertices lie on
    # the wall of the bore I said I drilled".  Nothing else would have caught it.
    if not HAVE_BPY:
        print("   SKIPPED: needs Blender (run with -b -P this file -- --selftest)")
    else:
        hero = None
        for q in ps:
            if q.sec.kind == "H" and q.spare_holes:
                hero = q
                break
        hero.lod = 3
        coll = _coll(COLL + "/Selftest")
        obj, _st = build_one(hero, coll, [mat_galv(), mat_fastener(),
                                          mat_conc()],
                             name=PFX + "SELFTEST")
        me = obj.data
        nv = len(me.vertices)
        co = np.empty(nv * 3, np.float32)
        me.vertices.foreach_get("co", co)
        co = co.reshape(-1, 3).astype(float)
        _acc, cutters = post_acc(hero, 3)
        onbore = 0
        holes_hit = 0
        for c in cutters:
            o = np.asarray(c["o"], float)
            ax = unit(c["a"])
            d = co - o[None, :]
            t = d @ ax
            rad = np.linalg.norm(d - np.outer(t, ax), axis=1)
            n_on = int(((np.abs(rad - c["r"]) < 0.002)
                        & (t > -0.005) & (t < c["depth"] + 0.005)).sum())
            onbore += n_on
            holes_hit += (n_on >= 8)
        print("   post %s: %d cutters, %d of them have a bore wall in the mesh, "
              "%d vertices on bores" % (hero.name, len(cutters), holes_hit,
                                        onbore))
        chk("EVERY declared hole has a real bore wall in the mesh",
            holes_hit == len(cutters) and onbore > 8 * len(cutters),
            "%d/%d holes, %d bore vertices" % (holes_hit, len(cutters), onbore))
        bpy.data.objects.remove(obj, do_unlink=True)

    print("\n7. DETERMINISM")
    _POSTS.clear()
    again = post_sites()
    same = (len(again) == len(ps)
            and all(abs(a.lean_deg - b.lean_deg) < 1e-12
                    and a.sec.name == b.sec.name and a.tag_no == b.tag_no
                    for a, b in zip(again, ps)))
    chk("rebuilding gives the same population", same)

    print("\n" + "=" * 78)
    print("SELFTEST %s" % ("PASS" if ok[0] else "FAIL"))
    print("=" * 78)
    return ok[0]


