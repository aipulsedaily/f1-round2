def _resample_loop(loop, k):
    P, N, T, A = loop
    tot = float(A[-1] + np.linalg.norm(P[0] - P[-1]))
    a = np.concatenate([A, [tot]])
    q = np.linspace(0.0, tot, k, endpoint=False)
    Pp = np.stack([np.interp(q, a, np.concatenate([P[:, i], P[:1, i]]))
                   for i in range(2)], axis=1)
    Nn = np.stack([np.interp(q, a, np.concatenate([N[:, i], N[:1, i]]))
                   for i in range(2)], axis=1)
    Nn /= np.maximum(np.linalg.norm(Nn, axis=1)[:, None], 1e-9)
    Tt = np.interp(q, a, np.concatenate([T, T[:1]])).round().astype(np.int32)
    return Pp, Nn, Tt, q


def zinc_field(p, z, arcp, tag, lod, sec_per):
    """Radial displacement (M,K) in metres, and the `drip` attribute (M,K).

    Hot-dip galvanising leaves the steel with a coat that is NOT uniform.  It
    pools in the root fillets, thins on the toes, and — because the section
    comes out of a 450 C bath and drains — freezes into RUNS that stream toward
    whichever end was down.  A 1.2 mm run is 1.7 px, which sounds like nothing
    until a 12.5 deg sun rakes along 4.8 m of them.

    This is displacement of the swept surface along its own outward normal.  It
    costs no extra topology and it is the difference between a galvanised post
    and a grey one.
    """
    M, K = len(z), len(arcp)
    L = LOD_SPEC[lod]
    disp = np.zeros((M, K))
    drip = np.zeros((M, K))
    # 1. pooling in the roots, thinning on the toes
    pool = np.zeros(K)
    for t, v in ((T_ROOT, 0.00016), (T_FLANGE_IN, 0.00004),
                 (T_TOE, -0.00006), (T_SHS_BORE, -0.00003)):
        pool[tag == t] = v
    disp += pool[None, :]
    if not L["drips"]:
        return disp, drip
    zd = z if p.dip_down else (p.stand_h - z)
    zd = zd - zd.min()
    span = max(1e-3, zd.max())
    nrun = 5 + rint(0, 5, p.seed, 311)
    for i in range(nrun):
        a0 = rnd(0.0, sec_per, p.seed, 313 + i * 7)
        sg = rnd(0.0035, 0.0105, p.seed, 317 + i * 7)
        amp = rnd(0.00030, 0.00185, p.seed, 331 + i * 7)
        z0 = rnd(0.05, 0.95, p.seed, 337 + i * 7) * span
        da = np.abs(arcp - a0)
        da = np.minimum(da, sec_per - da)
        w = np.exp(-0.5 * (da / sg) ** 2)
        # the run starts somewhere and thickens all the way down, then ends in
        # a teardrop where the surface tension held the last of it
        v = clamp01((zd - z0) / max(0.35 * span, 1e-3)) ** 0.7
        tear = np.exp(-0.5 * ((zd - z0 * 0.35) / (0.045 + 0.05 * span)) ** 2)
        prof = amp * (0.35 * v + 0.85 * tear * (zd < z0 * 0.75))
        prof = prof + amp * 0.30 * v * (0.5 + fbm1(zd * 26.0 + i * 13.0,
                                                   seed=p.seed + i, oct=3))
        d = prof[:, None] * w[None, :]
        disp += d
        drip = np.maximum(drip, d / max(amp, 1e-9))
    # 2. icicles at the end that hung down in the bath
    nic = 3 + rint(0, 6, p.seed, 401)
    for i in range(nic):
        a0 = rnd(0.0, sec_per, p.seed, 409 + i * 5)
        sg = rnd(0.0022, 0.0060, p.seed, 419 + i * 5)
        ln = rnd(0.0030, 0.0090, p.seed, 431 + i * 5)
        da = np.abs(arcp - a0)
        da = np.minimum(da, sec_per - da)
        w = np.exp(-0.5 * (da / sg) ** 2)
        v = np.exp(-((zd / (0.010 + ln)) ** 1.6))
        d = (ln * 0.55) * v[:, None] * w[None, :]
        disp += d
        drip = np.maximum(drip, np.minimum(1.0, d / max(ln * 0.3, 1e-9)))
    # 3. mill scale roughness under the zinc: sub-pixel but it breaks the
    #    specular into something that is not a mirror
    disp += 0.00007 * (fbm1(z[:, None] * 130.0 + arcp[None, :] * 220.0,
                            seed=p.seed + 7, oct=3) - 0.5)
    return disp, drip


def post_shell(acc, p, lod, mat=0):
    """Sweep the rolled section along the post's own curve."""
    L = LOD_SPEC[lod]
    sec = p.sec
    # A PLATED POST DOES NOT GO INTO THE GROUND.  Its steel is welded to the
    # TOP of a 16 mm plate and stops there; the first version ran it 15 mm
    # THROUGH the plate, so the section poked out underneath and the fillet
    # weld welded a post to a hole.
    z0 = (BASE_PLATE_T if p.base_kind == "plate" else -p.embed)
    z1 = p.stand_h
    r = L["ref"]
    refine = []
    if r > 0.0:
        refine += [(0.0, 0.28, r), (z1, 0.10, r), (z0, 0.06, r)]
        for cz in p.cleat_z:
            refine.append((cz, 0.085, r))
        for hz in HEAD_ROWS:
            refine.append((hz, 0.045, r))
        if p.damaged:
            refine.append((p.kink_z, 0.22, r * 0.9))
        if p.splice_z:
            refine.append((p.splice_z, 0.18, r))
        for sh in p.spare_holes:
            refine.append((sh["z"], 0.030, min(0.010, r)))
    # THE BURIED 1.2 m IS NEVER SEEN.  It exists because the collar item cuts
    # ground around it and because a post that stops at z = 0 has no shadow in
    # its own hole -- but it gets 400 mm stations, not 55.
    zs = stations(max(z0, -0.06), z1, L["stat"], refine)
    if z0 < -0.06:
        zs = np.unique(np.concatenate([np.arange(z0, -0.06, 0.40), [z0], zs]))
    Cc, eu, ev = post_frames(p, zs)
    loops = section_loops(sec, lod)
    km = L["kmax"]
    if km:
        loops = [_resample_loop(l, min(km, len(l[0]))) for l in loops]
    if len(loops) == 2:
        loops = [loops[0], _resample_loop(loops[1], len(loops[0][0]))]
    caps = []
    for li, (P2, N2, TG, A2) in enumerate(loops):
        K = len(P2)
        per = float(A2[-1] + np.linalg.norm(P2[0] - P2[-1]))
        disp, drip = zinc_field(p, zs, A2, TG, lod, per)
        if li == 1:
            disp = -disp * 0.35        # the bore drained, it did not pool
        # rolling tolerance: the flanges of a real section are not square to
        # the web.  +-1.2 mm over the flange width, constant up the post
        # because it is a property of the ROLLS, not of the erection.
        oos = 0.0012 * (h01(p.seed, 443) - 0.5) * 2.0
        skew = oos * (P2[:, 0] / max(1e-6, np.abs(P2[:, 0]).max())) \
            * np.sign(P2[:, 1])
        # local buckle at an impact
        if p.damaged and p.buckle > 0.0:
            bz = np.exp(-0.5 * ((zs - p.kink_z) / 0.075) ** 2)
            side = np.sign(math.sin(math.radians(p.kink_deg)))
            fl = (np.sign(P2[:, 1]) == -side) & (TG != T_WEB)
            disp = disp - (p.buckle * bz)[:, None] * fl[None, :].astype(float) \
                * (0.4 + 0.6 * np.cos(np.clip(P2[:, 0] / max(sec.B * .5, 1e-6),
                                              -1, 1) * 1.4))[None, :]
        Pd = P2[None, :, :] + N2[None, :, :] * (disp + skew[None, :])[:, :, None]
        V = (Cc[:, None, :]
             + eu[:, None, :] * Pd[:, :, 0][:, :, None]
             + ev[:, None, :] * Pd[:, :, 1][:, :, None])
        M = len(zs)
        crev = np.array([CREV_BY_TAG.get(int(t), 0.2) for t in TG])
        edg = np.array([EDGE_BY_TAG.get(int(t), 0.1) for t in TG])
        expo = clamp01(0.5 + 0.5 * N2[:, 1])
        hz = np.tile(zs[:, None], (1, K))
        acc.add(V.reshape(-1, 3), quads=ring_faces(M, K, closed=True), mat=mat,
                kind=K_STEEL, arc=hz.ravel(),
                ang=np.tile((A2 / max(per, 1e-9))[None, :], (M, 1)).ravel(),
                hz=hz.ravel(),
                expo=np.tile(expo[None, :], (M, 1)).ravel(),
                crev=np.tile(crev[None, :], (M, 1)).ravel(),
                edge=np.tile(edg[None, :], (M, 1)).ravel(),
                drip=drip.ravel(),
                bare=0.0, dent=(1.0 if p.damaged else 0.0))
        caps.append((acc.n - M * K, K, M, V))
    # --- end caps ------------------------------------------------------------
    if len(caps) == 1:
        b, K, M, V = caps[0]
        acc.add(np.zeros((0, 3)))
        # reuse the swept vertices by index: bottom reversed, top forward
        acc._L.append(np.concatenate([np.arange(b + K - 1, b - 1, -1),
                                      np.arange(b + (M - 1) * K, b + M * K)]))
        acc._T.append(np.array([K, K], np.int32))
        acc._M.append(np.array([mat, mat], np.int32))
        acc.nf += 2
    else:
        (b0, K, M, _), (b1, K1, M1, _) = caps
        for (r0, r1, rev) in ((b0, b1, True), (b0 + (M - 1) * K,
                                               b1 + (M1 - 1) * K1, False)):
            j = np.arange(K)
            j1 = (j + 1) % K
            q = np.stack([r0 + j, r0 + j1, r1 + j1, r1 + j], axis=1)
            if rev:
                q = q[:, ::-1]
            acc._L.append(q.ravel())
            acc._T.append(np.full(K, 4, np.int32))
            acc._M.append(np.full(K, mat, np.int32))
            acc.nf += K
    return zs


